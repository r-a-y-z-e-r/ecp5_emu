"""Generate HI12: pin-clock startup counts and PLL-observed divider phase."""
import argparse

VARIANTS = ('none_default', 'none_2', 'none_35', 'sync_2', 'sync_35')

# HY01's working external CLKOP feedback profile and analog attributes.
# 25 -> 100 MHz, 600 MHz VCO. The unused HY01 CLKOS output is omitted.
PLL = '''  wire observer, locked;
  (* FREQUENCY_PIN_CLKI="25", FREQUENCY_PIN_CLKOP="100",
     ICP_CURRENT="12", LPF_RESISTOR="8",
     MFG_ENABLE_FILTEROPAMP="1", MFG_GMCREF_SEL="2" *)
  EHXPLLL #(.PLLRST_ENA("DISABLED"), .INTFB_WAKE("DISABLED"),
    .STDBY_ENABLE("DISABLED"), .DPHASE_SOURCE("DISABLED"),
    .OUTDIVIDER_MUXA("DIVA"), .OUTDIVIDER_MUXB("DIVB"),
    .OUTDIVIDER_MUXC("DIVC"), .OUTDIVIDER_MUXD("DIVD"),
    .CLKI_DIV(1), .CLKFB_DIV(4), .CLKOP_DIV(6),
    .CLKOP_CPHASE(2), .CLKOP_FPHASE(0), .CLKOP_ENABLE("ENABLED"),
    .FEEDBK_PATH("CLKOP")) observer_pll(
    .CLKI(clk), .CLKFB(observer), .CLKOP(observer), .LOCK(locked),
    .RST(1'b0), .STDBY(1'b0), .PHASESEL0(1'b0), .PHASESEL1(1'b0),
    .PHASEDIR(1'b1), .PHASESTEP(1'b1), .PHASELOADREG(1'b1),
    .PLLWAKESYNC(1'b0), .ENCLKOP(1'b0), .ENCLKOS(1'b0),
    .ENCLKOS2(1'b0), .ENCLKOS3(1'b0));
'''


def generate(variant):
    assert variant in VARIANTS
    control = variant.startswith('sync')
    ratio = '3.5' if variant.endswith('35') else '2.0'
    params = '' if variant == 'none_default' else f'#(.DIV("{ratio}"))'
    clock = ('  wire divided_input;\n  (* BEL="X0/Y46/ECLKSYNC1_BK7" *) ECLKSYNCB sync(.ECLKI(clk), .STOP(1\'b0), .ECLKO(divided_input));'
             if control else '  wire divided_input = clk;')
    return '''// Generated by hi12_gen.py. No GSR primitive or explicit CLKDIVF GSR.
module top(input clk, output ftdi_rxd);
@PLL@
  wire support_clock;
  DCCA support_buffer(.CLKI(clk), .CE(1'b1), .CLKO(support_clock));
@CLOCK@
  wire q;
  (* BEL="X0/Y46/CLKDIV1" *) CLKDIVF @PARAMS@ u(.CLKI(divided_input), .RST(1'b0), .ALIGNWD(1'b0), .CDIVX(q));
  // build.py disables GSR on EVERY support/counter FF after synthesis.
  // These counters start at configuration, independently of PLL LOCK.
  reg freeze=0;
  (* keep=1 *) reg [31:0] input_count=0, rising_count=0, falling_count=0;
  always @(posedge support_clock) if (!freeze) input_count<=input_count+1'b1;
  always @(posedge q) if (!freeze) rising_count<=rising_count+1'b1;
  always @(negedge q) if (!freeze) falling_count<=falling_count+1'b1;

  // Observe raw CLKI and CDIVX at 100 MHz (10 ns resolution).
  // Mid/final snapshots are taken during the low half of CLKI, after two
  // consecutive low samples. All counted clocks have edges only at CLKI
  // edges. Inspect the phase record to confirm that margin on the board.
  reg [1:0] low_history=3;
  reg [1:0] lock_history=0;
  reg [8:0] phase_count=0;
  reg [511:0] phase=0;
  reg [95:0] mid=0, final_counts=0;
  reg mid_done=0, finished=0;
  reg observer_seen=0;
  reg [3:0] settle=0;
  always @(posedge observer) begin
    observer_seen<=1;
    low_history<={low_history[0],clk};
    lock_history<={lock_history[0],locked};
    if (&lock_history && !phase_count[8] && input_count>=32'd262144) begin
      phase<={phase[509:0],clk,q}; phase_count<=phase_count+1'b1;
    end
    if (&lock_history && !low_history[0] && !clk) begin
      if (!mid_done && input_count>=32'd524288) begin
        mid<={input_count,rising_count,falling_count}; mid_done<=1;
      end
      if (mid_done && !freeze && input_count>=32'd1048576) freeze<=1;
    end
    // Wait for counter enables to settle, then take the frozen snapshot.
    if (freeze && !finished) begin
      settle<=settle+1'b1;
      if (&settle) begin
        final_counts<={input_count,rising_count,falling_count}; finished<=1;
      end
    end
  end

  // UART is driven ONLY by the pin-clock domain: never wait for the PLL.
  // Before completion, HB reports synchronized flags and a pin-edge count.
  // After completion, repeat the immutable 704-bit startup record.
  reg [1:0] ready=0, lock_ref=0, observer_ref=0, mid_ref=0, freeze_ref=0;
  always @(posedge support_clock) begin
    ready<={ready[0],finished};
    lock_ref<={lock_ref[0],locked};
    observer_ref<={observer_ref[0],observer_seen};
    mid_ref<={mid_ref[0],mid_done};
    freeze_ref<={freeze_ref[0],freeze};
  end
  wire [7:0] status_flags={3'b0,ready[1],freeze_ref[1],mid_ref[1],observer_ref[1],lock_ref[1]};
  wire [703:0] payload={mid,final_counts,phase};
  reg [703:0] word=0;
  reg [39:0] heartbeat=0;
  reg [7:0] ci=8'hff, baud=0;
  reg [3:0] bitn=0;
  reg busy=0, sending=0, full_record=0;
  reg [9:0] shift=10'h3ff;
  assign ftdi_rxd=busy ? shift[0] : 1'b1;
  function [7:0] hex(input [3:0] n);
    hex=n<10 ? 8'h30+n : 8'h41+n-10;
  endfunction
  reg [7:0] ch;
  always @* begin
    if (ci==0) ch="H";
    else if (ci==1) ch=full_record ? "C" : "B";
    else if (ci==2) ch="@ID@";
    else if (ci==3) ch=" ";
    else if (full_record) begin
      if (ci<180) ch=hex(word[703:700]);
      else if (ci==180) ch=8'h0d;
      else ch=8'h0a;
    end else begin
      if (ci==6) ch=" ";
      else if (ci<15) ch=hex(heartbeat[39:36]);
      else if (ci==15) ch=8'h0d;
      else ch=8'h0a;
    end
  end
  always @(posedge support_clock) begin
    if (!sending) begin
      full_record<=&ready; word<=payload;
      heartbeat<={status_flags,input_count}; ci<=0; sending<=1;
    end
    else if (!busy) begin shift<={1'b1,ch,1'b0}; bitn<=0; baud<=216; busy<=1; end
    else if (baud!=0) baud<=baud-1'b1;
    else begin
      baud<=216; shift<={1'b1,shift[9:1]}; bitn<=bitn+1'b1;
      if (bitn==9) begin
        busy<=0; ci<=ci+1'b1;
        if (full_record && ci>=4 && ci<180) word<=word<<4;
        if (!full_record && ci>=4 && ci<15 && ci!=6) heartbeat<=heartbeat<<4;
        if (ci==(full_record ? 181 : 16)) sending<=0;
      end
    end
  end
endmodule
'''.replace('@PLL@', PLL).replace('@CLOCK@', clock).replace('@PARAMS@', params).replace('@ID@', str(VARIANTS.index(variant)))


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('variant', choices=VARIANTS)
    print(generate(p.parse_args().variant), end='')
