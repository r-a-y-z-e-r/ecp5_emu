"""Generate HI11 UART output-delay probes; no hardware access.

Usage: python3 hi11_gen.py f|g|fabric > /tmp/hi11.v
F: OFS1P3BX -> DELAYF(10); G: OFS1P3BX -> DELAYG(127);
B: fabric FF -> DELAYG(127). See README.md for records and sample alignment.
"""
import argparse

SAMPLES = 2048
# Exclusive end, LOADN, MOVE expression, DIRECTION. Controls are registered.
PHASES = [
    (16, 1, "0", 1), (48, 1, "u[1:0] == 0", 1),
    (52, 1, "0", 0), (56, 1, "0", 1),
    (60, 0, "0", 0), (64, 1, "0", 0),
    (624, 1, "u[1:0] == 0", 0),
    (628, 0, "0", 1), (632, 1, "0", 1),
    (1192, 1, "u[1:0] == 0", 1),
    (1200, 1, "0", 0), (1208, 1, "0", 1),
    (1212, 0, "0", 0), (1216, 1, "0", 0),
    (1248, 1, "1", 0), (1256, 1, "0", 0),
    (1260, 1, "0", 1), (1292, 1, "1", 1), (1300, 1, "0", 1),
    (1304, 0, "0", 0), (1308, 1, "0", 0), (1388, 1, "u[1] == 0", 0),
    (1420, 0, "u[1] == 0", 0), (2048, 1, "0", 0),
]


def controls():
    """Pre-edge samples: initial controls, then registered program step i-1."""
    result = [(1, 0, 1)]
    for u in range(SAMPLES - 1):
        for end, loadn, move, direction in PHASES:
            if u < end:
                value = int(u % 4 == 0) if move == "u[1:0] == 0" else (
                    int(u % 4 < 2) if move == "u[1] == 0" else int(move))
                result.append((loadn, value, direction))
                break
    return result


def generate(variant):
    ident = {"f": "F", "g": "G", "fabric": "B"}[variant]
    register = ('(* syn_useioff=0 *) reg registered_tx=1;\n'
                '  always @(posedge clk_25mhz) registered_tx<=tx;' if variant == "fabric" else
                'wire registered_tx;\n'
                "  OFS1P3BX tx_reg(.SCLK(clk_25mhz), .SP(1'b1), .PD(1'b0),\n"
                '                    .D(tx), .Q(registered_tx));')
    delay = ('DELAYF #(.DEL_MODE("USER_DEFINED"), .DEL_VALUE(10)) tx_delay(\n'
             '    .A(registered_tx), .Z(ftdi_rxd), .LOADN(loadn), .MOVE(move),\n'
             '    .DIRECTION(direction), .CFLAG(flag));' if variant == "f" else
             'DELAYG #(.DEL_MODE("USER_DEFINED"), .DEL_VALUE(127)) tx_delay(\n'
             '    .A(registered_tx), .Z(ftdi_rxd));\n  assign flag=0;')
    program = '\n'.join(
        f"    {'if' if i == 0 else 'else if'} (u < {end}) "
        f"begin loadn<=1'b{loadn}; move<=({move}); direction<=1'b{direction}; end"
        for i, (end, loadn, move, direction) in enumerate(PHASES))
    return f'''// HI11 {ident}; generated by hi11_gen.py. Board observations pending.
module top(input clk_25mhz, output ftdi_rxd);
  reg loadn=1, move=0, direction=1;
  wire flag;
  reg [15:0] warm=0;
  reg run=0;
  reg [11:0] u=0;
  always @(posedge clk_25mhz) begin
    if (!run) begin
      warm<=warm+1'b1;
      if (&warm) run<=1;
    end else if (u<2048) u<=u+1'b1;
  end
  always @(posedge clk_25mhz) if (run) begin
{program}
  end
  // Capture stable controls/CFLAG before this edge updates the controls.
  reg [3:0] record [0:2047];
  reg [3:0] checksum=0;
  wire [3:0] sample={{loadn,move,direction,flag}};
  always @(posedge clk_25mhz) if (run && u<2048) begin
    record[u[10:0]]<=sample;
    checksum<=checksum^sample;
  end
  wire done=u==2048;
  function [7:0] hex(input [3:0] v);
    hex=v<10 ? 8'h30+v : 8'h37+v;
  endfunction
  // H11{ident}, eight sequence digits, 2048 sample nibbles, XOR nibble, CR LF.
  reg [31:0] sequence_number=0;
  reg [11:0] ci=0;
  wire [10:0] read_address=ci-12;
  reg [3:0] read_sample=0;
  always @(posedge clk_25mhz) read_sample<=record[read_address];
  reg [7:0] ch;
  always @* begin
    if (ci==0) ch="H";
    else if (ci==1 || ci==2) ch="1";
    else if (ci==3) ch="{ident}";
    else if (ci<12) ch=hex(sequence_number[31-4*(ci-4) -: 4]);
    else if (ci<2060) ch=hex(read_sample);
    else if (ci==2060) ch=hex(checksum);
    else if (ci==2061) ch=8'h0d;
    else ch=8'h0a;
  end
  (* syn_useioff=0 *) reg tx=1;
  reg busy=0;
  reg [7:0] baud=0;
  reg [3:0] bitn=0;
  reg [9:0] shift=10'h3ff;
  reg [22:0] pause=0;
  reg [1:0] gap=2;
  always @(posedge clk_25mhz)
    if (!busy) begin
      if (pause!=0) pause<=pause-1'b1;
      else if (gap!=0) gap<=gap-1'b1;
      else if (done) begin
        shift<={{1'b1,ch,1'b0}};
        busy<=1; baud<=0; bitn<=0;
      end
    end else if (baud==216) begin
      baud<=0; tx<=shift[0]; shift<={{1'b1,shift[9:1]}}; bitn<=bitn+1'b1;
      if (bitn==9) begin
        busy<=0; gap<=2; // Allow the synchronous record read to settle.
        if (ci==2062) begin
          ci<=0; sequence_number<=sequence_number+1'b1; pause<=23'd2500000;
        end else ci<=ci+1'b1;
      end
    end else baud<=baud+1'b1;
  {register}
  {delay}
endmodule
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('variant', choices=['f', 'g', 'fabric'])
    print(generate(parser.parse_args().variant), end='')
