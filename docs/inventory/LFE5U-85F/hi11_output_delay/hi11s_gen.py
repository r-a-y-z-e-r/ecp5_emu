"""Generate HI11s startup comparisons, retaining the original two-lane builds.
Usage: python3 hi11s_gen.py 1|10|63|64|100|127 > /tmp/hi11s.v
TX: OFS1P3BX -> DELAYF -> L4. Input: J1 GP9/A2 -> DELAYF -> sample RAM.
Values 1/63/64/127 also include bottom-bank FIRE1/R1 as a third DELAYF.
All delays share registered controls; there is no load before 140 down pulses.
"""
import argparse

SAMPLES = 2048
VALUES = {'0': 10, '1': 100, '2': 1, '3': 63, '4': 64, '5': 127}
THREE_LANE_IDS = frozenset('2345')
PHASES = [
    (16, 1, '0', 1), (576, 1, 'u[1:0] == 0', 1),
    (592, 1, '0', 1), (600, 1, '0', 0), (608, 1, '0', 1),
    (612, 0, '0', 0), (616, 1, '0', 0),
    (1176, 1, 'u[1:0] == 0', 0), (1192, 1, '0', 1),
    (1196, 0, '0', 1), (1200, 1, '0', 1),
    (1760, 1, 'u[1:0] == 0', 1), (1776, 1, '0', 0),
    (2048, 1, '0', 1),
]


def controls():
    result = [(1, 0, 1)]
    for u in range(SAMPLES - 1):
        for end, loadn, move, direction in PHASES:
            if u < end:
                result.append((loadn, int(u % 4 == 0) if move == 'u[1:0] == 0'
                               else int(move), direction))
                break
    return result


def generate(value):
    ident = next(ident for ident, configured in VALUES.items() if configured == value)
    three_lanes = ident in THREE_LANE_IDS
    bottom_port = ', input bottom_input' if three_lanes else ''
    bottom_delay = (f'''  wire bottom_flag, delayed_bottom;
  DELAYF #(.DEL_MODE("USER_DEFINED"), .DEL_VALUE({value})) bottom_delay(
    .A(bottom_input), .Z(delayed_bottom), .LOADN(loadn), .MOVE(move),
    .DIRECTION(direction), .CFLAG(bottom_flag));
''' if three_lanes else '')
    sample_prefix = 'delayed_bottom,bottom_flag' if three_lanes else "2'b0"
    sample_comment = ('''  // byte = {bottom_data, bottom_flag, side_data, LOADN, MOVE, DIRECTION, side_flag, output_flag}.
''' if three_lanes else '''  // Keep input Z as data in every record, alongside the two CFLAG outputs.
  // byte = {reserved[1:0], delayed_input, LOADN, MOVE, DIRECTION, input_flag, output_flag}.
''')
    program = '\n'.join(
        f"    {'if' if i == 0 else 'else if'} (u < {end}) "
        f"begin loadn<=1'b{loadn}; move<=({move}); direction<=1'b{direction}; end"
        for i, (end, loadn, move, direction) in enumerate(PHASES))
    return f'''// HI11s DEL_VALUE={value}; generated by hi11s_gen.py. Board run pending.
module top(input clk_25mhz, input side_input{bottom_port}, output ftdi_rxd);
  reg loadn=1, move=0, direction=1;
  wire output_flag, input_flag, delayed_input;
  reg [15:0] warm=0;
  reg run=0;
  reg [11:0] u=0;
  always @(posedge clk_25mhz) begin
    if (!run) begin
      warm<=warm+1'b1;
      if (&warm) run<=1;
    end else if (u<2048) u<=u+1'b1;
  end
  always @(posedge clk_25mhz) if (run) begin
{program}
  end
  DELAYF #(.DEL_MODE("USER_DEFINED"), .DEL_VALUE({value})) input_delay(
    .A(side_input), .Z(delayed_input), .LOADN(loadn), .MOVE(move),
    .DIRECTION(direction), .CFLAG(input_flag));
{bottom_delay}{sample_comment}  wire [7:0] sample={{{sample_prefix},delayed_input,loadn,move,direction,input_flag,output_flag}};
  reg [7:0] record [0:2047];
  reg [7:0] checksum=0;
  always @(posedge clk_25mhz) if (run && u<2048) begin
    record[u[10:0]]<=sample;
    checksum<=checksum^sample;
  end
  wire done=u==2048;
  function [7:0] hex(input [3:0] v);
    hex=v<10 ? 8'h30+v : 8'h37+v;
  endfunction
  // H11S{ident}, eight sequence digits, 4096 payload digits, XOR byte, CR LF.
  reg [31:0] sequence_number=0;
  reg [12:0] ci=0;
  wire [12:0] payload_index=ci-13;
  wire [10:0] read_address=payload_index[11:1];
  reg [7:0] read_sample=0;
  always @(posedge clk_25mhz) read_sample<=record[read_address];
  reg [7:0] ch;
  always @* begin
    if (ci==0) ch="H";
    else if (ci==1 || ci==2) ch="1";
    else if (ci==3) ch="S";
    else if (ci==4) ch="{ident}";
    else if (ci<13) ch=hex(sequence_number[31-4*(ci-5) -: 4]);
    else if (ci<4109) ch=hex(payload_index[0] ? read_sample[3:0] : read_sample[7:4]);
    else if (ci==4109) ch=hex(checksum[7:4]);
    else if (ci==4110) ch=hex(checksum[3:0]);
    else if (ci==4111) ch=8'h0d;
    else ch=8'h0a;
  end
  (* syn_useioff=0 *) reg tx=1;
  reg busy=0;
  reg [7:0] baud=0;
  reg [3:0] bitn=0;
  reg [9:0] shift=10'h3ff;
  reg [22:0] pause=0;
  reg [1:0] gap=2;
  always @(posedge clk_25mhz)
    if (!busy) begin
      if (pause!=0) pause<=pause-1'b1;
      else if (gap!=0) gap<=gap-1'b1;
      else if (done) begin
        shift<={{1'b1,ch,1'b0}};
        busy<=1; baud<=0; bitn<=0;
      end
    end else if (baud==216) begin
      baud<=0; tx<=shift[0]; shift<={{1'b1,shift[9:1]}}; bitn<=bitn+1'b1;
      if (bitn==9) begin
        busy<=0; gap<=2;
        if (ci==4112) begin
          ci<=0; sequence_number<=sequence_number+1'b1; pause<=23'd2500000;
        end else ci<=ci+1'b1;
      end
    end else baud<=baud+1'b1;
  wire registered_tx;
  OFS1P3BX tx_reg(.SCLK(clk_25mhz), .SP(1'b1), .PD(1'b0),
                    .D(tx), .Q(registered_tx));
  DELAYF #(.DEL_MODE("USER_DEFINED"), .DEL_VALUE({value})) output_delay(
    .A(registered_tx), .Z(ftdi_rxd), .LOADN(loadn), .MOVE(move),
    .DIRECTION(direction), .CFLAG(output_flag));
endmodule
'''


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('value', type=int, choices=sorted(VALUES.values()))
    print(generate(parser.parse_args().value), end='')
