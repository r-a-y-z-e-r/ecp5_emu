"""Write hd08z.v: what Z = 7 (OP[6:4] = 111) reads, against RNDPAT and GSR
(HD08z). Usage: python3 hd08z_gen.py > hd08z.v

The port lists of MULT18X18D and ALU54B are bit-per-port, so the file is
generated."""

ROW = 58
# name, block X, second slice, RNDPAT, GSR of the ALU and its MULT18
ALUS = [
    ("z0", 13, False, 0x00000000000000, "ENABLED"),
    ("z1", 13, True, 0x00000000000000, "DISABLED"),
    ("z2", 22, False, 0x0123456789ABC5, "ENABLED"),
    ("z3", 22, True, 0x00000000000010, "DISABLED"),
    ("z4", 31, False, 0x00000000000100, "ENABLED"),
    ("z5", 31, True, 0x00000000000002, "DISABLED"),
    ("z6", 40, False, 0x20000000000000, "ENABLED"),
    ("z7", 40, True, 0x3FFFFFFFFFFFF0, "DISABLED"),
]
READ_Z7 = "11'b01001111111"  # R = Z: Z = 7, X and Y zero, a sum


def bus(port, net, n, lo=0, plo=0):
    return ", ".join(f".{port}{k + plo}({net}[{k + lo}])" for k in range(n))


def zeros(port, n):
    return ", ".join(f".{port}{k}(1'b0)" for k in range(n))


CONTROLS = ("CLK0(clk_25mhz), .CLK1(1'b0), .CLK2(1'b0), .CLK3(1'b0), "
            + ", ".join(f".CE{k}(1'b1)" for k in range(4)) + ", "
            + ", ".join(f".RST{k}(1'b0)" for k in range(4)))

print(f"""// HD08z slice: what Z = 7 reads, against RNDPAT and GSR. Generated by
// hd08z_gen.py.
// Eight ALU54B in four DSP blocks of row {ROW} (X 13, 22, 31, 40), each with
// its two MULT18X18D (no registers, every input 0), computing R = Z with
// Z = 7 (OP = 01001111111). Output and flag registers on CLK0; CE high, RST
// low.
//   name  block  slice   RNDPAT          GSR (ALU and MULT18)
""" + "".join(f"//   {n}    {bx}     {'second' if s else 'first '}  {r:014X}  {g}\n" for n, bx, s, r, g in ALUS) + """// Line "Z<n><14 hex>" per ALU in turn: the ALU's number n, then its R[53:0]
// padded to 56 bits; z0 to z7, again and again.
module top(input clk_25mhz, output ftdi_rxd);
  wire [10:0] op = """ + READ_Z7 + ";")
for name, bx, second, rnd, gsr in ALUS:
    x = bx + 4 * second
    m = [f"{name}_m0", f"{name}_m1"]
    print(f"""  wire [35:0] {m[0]}_p, {m[1]}_p;
  wire [17:0] {m[0]}_roa, {m[0]}_rob, {m[1]}_roa, {m[1]}_rob;
  wire {m[0]}_sp, {m[1]}_sp;
  wire [53:0] {name}_r;""")
    for k, mm in enumerate(m):
        print(f"""  (* BEL="X{x + k}/Y{ROW}/MULT18_{4 * second + k}" *)
  MULT18X18D #(.REG_INPUTA_CLK("NONE"), .REG_INPUTB_CLK("NONE"), .REG_INPUTC_CLK("NONE"),
      .REG_PIPELINE_CLK("NONE"), .REG_OUTPUT_CLK("NONE"), .GSR("{gsr}"), .RESETMODE("SYNC"))
    {mm}({zeros("A", 18)}, {zeros("B", 18)}, {zeros("C", 18)},
      .SIGNEDA(1'b0), .SIGNEDB(1'b0), .SOURCEA(1'b0), .SOURCEB(1'b0), .{CONTROLS},
      {bus("P", mm + "_p", 36)}, {bus("ROA", mm + "_roa", 18)}, {bus("ROB", mm + "_rob", 18)},
      .SIGNEDP({mm}_sp));""")
    print(f"""  (* BEL="X{x + 3}/Y{ROW}/ALU54_{3 + 4 * second}" *)
  ALU54B #(.REG_OUTPUT0_CLK("CLK0"), .REG_OUTPUT1_CLK("CLK0"), .REG_FLAG_CLK("CLK0"),
      .RNDPAT("0x{rnd:014X}"), .GSR("{gsr}"), .RESETMODE("SYNC"))
    {name}({bus("A", m[0] + "_roa", 18)}, {bus("A", m[0] + "_rob", 18, 0, 18)},
      {bus("B", m[1] + "_roa", 18)}, {bus("B", m[1] + "_rob", 18, 0, 18)},
      {bus("MA", m[0] + "_p", 36)}, {bus("MB", m[1] + "_p", 36)},
      {zeros("C", 54)}, {", ".join(f".OP{k}(op[{k}])" for k in range(11))},
      .SIGNEDIA({m[0]}_sp), .SIGNEDIB({m[1]}_sp), .{CONTROLS},
      {bus("R", name + "_r", 54)});
""")
words = ", ".join(f"2'b0, {n}_r" for n, *_ in reversed(ALUS))
print(f"""  wire [447:0] all = {{{words}}};
  reg [2:0] which = 0;
  wire [55:0] word = all[56 * which +: 56];
  function [7:0] hex(input [3:0] v);
    hex = v < 10 ? 8'h30 + v : 8'h37 + v;
  endfunction
  // UART: "Z" + the ALU's number + 14 hex digits + CR LF, 115200 8N1.
  reg [4:0] ci = 0;
  reg [7:0] ch;
  always @* begin
    if (ci == 0) ch = "Z";
    else if (ci == 1) ch = 8'h30 + which;
    else if (ci < 16) ch = hex(word[55 - 4 * (ci - 2) -: 4]);
    else if (ci == 16) ch = 8'h0d;
    else ch = 8'h0a;
  end
  reg tx = 1, busy = 0;
  reg [7:0] baud = 0;
  reg [3:0] bitn = 0;
  reg [9:0] shift = 10'h3ff;
  always @(posedge clk_25mhz)
    if (!busy) begin
      shift <= {{1'b1, ch, 1'b0}};
      busy <= 1; baud <= 0; bitn <= 0;
    end else if (baud == 216) begin
      baud <= 0;
      tx <= shift[0];
      shift <= {{1'b1, shift[9:1]}};
      bitn <= bitn + 1;
      if (bitn == 9) begin
        busy <= 0;
        if (ci == 17) begin ci <= 0; which <= which + 1; end
        else ci <= ci + 1;
      end
    end else baud <= baud + 1;
  assign ftdi_rxd = tx;
endmodule""")
