"""Generate HC02 DCSC board tests; stdout is synthesizable Verilog.

Usage: python3 hc02_gen.py [--variant dynamic|static] > /tmp/hc02.v
dynamic: DCS0=POS, DCS1=NEG. static: DCS0=CLK0_LOW, DCS1=CLK1_HIGH.
Both DCSMODE attributes AND parameters are set; inspect the routed config.

One PLL: 25 MHz -> 600 MHz VCO -> 200 MHz sampler, 6.25 MHz CLK0,
4.6875 MHz CLK1. These clocks have different periods/phases but are related:
their relative phase repeats every 640 ns. No clock net is sampled as data.
Four-bit Gray counters count BOTH edges of each source and each DCS output.

UART: 115200 8N1 (25 MHz / 217 = 115207.37 baud), uppercase hexadecimal:
  D2 V QQQQQQQQ TTT SSSSSSSS [512 * WWWWWWWWWWWW] XXXXXXXXXXXX CR LF
Spaces above are explanatory, never transmitted. Exactly 6180 bytes/line.
V: 0=dynamic, 1=static; Q: sequence number modulo 2**32; T: first sample
with NEW controls (128..255); S: LFSR at request acceptance; X: XOR of all
512 sample words (48 bits). Sample 0 first, each word MS nibble first.

Word W (48 bits):
  47:44 = 0 (reserved), 43 = synchronized PLL LOCK,
  42 = MODESEL, 41:40 = SEL[1:0] (shared by the two DCS),
  39:36 = level-valid bits, 35:32 = inferred levels, in DCS1,DCS0,CLK1,CLK0 order,
  31:0 = eight 4-bit edge-count deltas, least significant first:
         CLK0 rise, CLK0 fall, CLK1 rise, CLK1 fall,
         DCS0 rise, DCS0 fall, DCS1 rise, DCS1 fall.
Each delta is modulo 16. Counts >1 and simultaneous rise/fall observations
are retained; pulses may be detected even if their two edges share a bin.
Sixteen same-polarity edges within one bin could alias to zero.

Alignment: sample k is the combinational observer value immediately BEFORE
fast edge k, including the current deltas and level AFTER those deltas.
SEL/MODESEL change by NBA at edge T-1: sample T-1 has old controls, T has new.
Two synchronizer stages, registered Gray decode and registered subtraction
plus this pre-edge read put a physical edge in sample k if it occurred in
(k-5,k-4] fast periods, absent extra metastability delay.
Use k-4.5 as its estimated time, with nominal +/-0.5 tick uncertainty; channel
skew/metastability can add a bin. Control time is T-1, without this delay.
The analyser compares source and output events with a configurable tolerance.

An unambiguous rise/fall establishes level=1/0 and validity. A bin containing
both polarities invalidates level until another unambiguous edge. Boot runs
SEL=01 and then 10 for 32768 fast cycles each after LOCK, so the static build
also gets a level anchor. Controls stay fixed during settling/capture/UART;
one change per window, random position, >=256 settling ticks before capture.
Three quarters of proposals alternate one-hot SEL with MODESEL=0; the rest
draw all three control bits from the LFSR, including MODESEL-only changes.
"""

import argparse
import sys

SAMPLES = 512
SAMPLE_BITS = 48
PAYLOAD_START = 22
PAYLOAD_END = PAYLOAD_START + SAMPLES * 12
LINE_BYTES = PAYLOAD_END + 14
MODES = {"dynamic": ("POS", "NEG"), "static": ("CLK0_LOW", "CLK1_HIGH")}


OBSERVER = r"""
// The clock is used only on flip-flop clock pins, never on a data pin.
module edge_observer(input fast, input observed,
  output reg [3:0] dr=0, output reg [3:0] df=0, output level, output valid);
  reg [3:0] rb=0, fb=0, rg=0, fg=0;
  wire [3:0] rn=rb+4'd1, fn=fb+4'd1;
  always @(posedge observed) begin rb<=rn; rg<=rn^(rn>>1); end
  always @(negedge observed) begin fb<=fn; fg<=fn^(fn>>1); end
  (* async_reg="true" *) reg [3:0] r1=0, r2=0, f1=0, f2=0;
  function [3:0] binary(input [3:0] g);
    binary={g[3], ^g[3:2], ^g[3:1], ^g};
  endfunction
  reg [3:0] r=0, f=0;
  reg [3:0] rp=0, fp=0;
  reg last_level=0, last_valid=0;
  assign level=(dr!=0 && df==0) ? 1'b1 :
               (df!=0 && dr==0) ? 1'b0 : last_level;
  assign valid=(dr!=0 && df!=0) ? 1'b0 :
               (dr!=0 || df!=0) ? 1'b1 : last_valid;
  always @(posedge fast) begin
    r1<=rg; r2<=r1; f1<=fg; f2<=f1;
    r<=binary(r2); f<=binary(f2);
    rp<=r; fp<=f; dr<=r-rp; df<=f-fp;
    last_level<=level; last_valid<=valid;
  end
endmodule
"""


def generate(variant="dynamic"):
    mode0, mode1 = MODES[variant]
    ident = int(variant == "static")
    observers = "\n".join(
        f"  wire [3:0] r{i}, f{i};\n"
        f"  edge_observer o{i}(.fast(fast), .observed({clock}), "
        f".dr(r{i}), .df(f{i}), .level(levels[{i}]), .valid(valids[{i}]));"
        for i, clock in enumerate(("c0", "c1", "d0", "d1"))
    )
    return f"""// HC02 {variant}; generated by hc02_gen.py. See its docstring for wire format.
module top(input clk_25mhz, output ftdi_rxd);
  wire fast, c0, c1, locked, d0, d1;
  // ecppll -i 25 -o 200 --clkout1 6.25 --clkout2 4.6875
  //        --phase1 37.5 --phase2 73.125
  (* FREQUENCY_PIN_CLKI="25", FREQUENCY_PIN_CLKOP="200",
     FREQUENCY_PIN_CLKOS="6.25", FREQUENCY_PIN_CLKOS2="4.6875",
     ICP_CURRENT="12", LPF_RESISTOR="8", MFG_ENABLE_FILTEROPAMP="1",
     MFG_GMCREF_SEL="2" *)
  EHXPLLL #(
    .PLLRST_ENA("DISABLED"), .INTFB_WAKE("DISABLED"), .STDBY_ENABLE("DISABLED"),
    .DPHASE_SOURCE("DISABLED"), .OUTDIVIDER_MUXA("DIVA"),
    .OUTDIVIDER_MUXB("DIVB"), .OUTDIVIDER_MUXC("DIVC"), .OUTDIVIDER_MUXD("DIVD"),
    .CLKI_DIV(1), .CLKFB_DIV(8), .FEEDBK_PATH("CLKOP"),
    .CLKOP_ENABLE("ENABLED"), .CLKOP_DIV(3), .CLKOP_CPHASE(1), .CLKOP_FPHASE(0),
    .CLKOS_ENABLE("ENABLED"), .CLKOS_DIV(96), .CLKOS_CPHASE(11), .CLKOS_FPHASE(0),
    .CLKOS2_ENABLE("ENABLED"), .CLKOS2_DIV(128), .CLKOS2_CPHASE(27), .CLKOS2_FPHASE(0)
  ) pll(.CLKI(clk_25mhz), .CLKFB(fast), .CLKOP(fast), .CLKOS(c0), .CLKOS2(c1),
    .RST(1'b0), .STDBY(1'b0), .PHASESEL0(1'b0), .PHASESEL1(1'b0),
    .PHASEDIR(1'b1), .PHASESTEP(1'b1), .PHASELOADREG(1'b1),
    .PLLWAKESYNC(1'b0), .ENCLKOP(1'b0), .LOCK(locked));

  reg [2:0] control=3'b001;
  (* BEL="X66/Y22/DCS0", DCSMODE="{mode0}" *)
  DCSC #(.DCSMODE("{mode0}")) dcs0(.CLK0(c0), .CLK1(c1),
    .SEL0(control[0]), .SEL1(control[1]), .MODESEL(control[2]), .DCSOUT(d0));
  (* BEL="X66/Y70/DCS1", DCSMODE="{mode1}" *)
  DCSC #(.DCSMODE("{mode1}")) dcs1(.CLK0(c0), .CLK1(c1),
    .SEL0(control[0]), .SEL1(control[1]), .MODESEL(control[2]), .DCSOUT(d1));

  wire [3:0] levels, valids;
{observers}
  (* async_reg="true" *) reg [1:0] lock_sync=0;
  wire [47:0] sample={{4'b0, lock_sync[1], control, valids, levels,
                        f3,r3,f2,r2,f1,r1,f0,r0}};

  // Bundled-data toggle handshake: metadata/RAM stay fixed until the next
  // request, which is sent only after the complete UART line has left.
  reg request=1, acknowledge=0;
  (* async_reg="true" *) reg [1:0] request_sync=0, ack_sync=0;
  reg [47:0] memory [0:{SAMPLES-1}];
  reg [31:0] lfsr=32'h48430201, win_seed=0;
  reg [8:0] trigger=128, index=0;
  reg [8:0] fire_index=125;
  reg [2:0] switch_parts=0;
  reg switch_now=0;
  reg capture_last=0;
  reg [47:0] checksum=0;
  reg [2:0] proposed=1;
  wire [2:0] random_control=(lfsr[4:3]!=2'b11) ?
      ((control[1:0]==1) ? 3'b010 : 3'b001) : lfsr[2:0];
  wire [2:0] next_control=(random_control==control) ?
      (control^3'b100) : random_control;
  localparam BOOT=0, IDLE=1, SETTLE=2, CAPTURE=3;
  // Explicit one-hot bits preserve configuration-time initialization.
  // Forcing Yosys FSM recoding would discard init and even remove BOOT.
  (* fsm_encoding="none" *) reg [3:0] fast_state=4'b0001;
  reg [15:0] warm=0;
  reg warm_mid=0, warm_done=0;
  reg [9:0] settle=0;
  reg settle_done=0;
  always @(posedge fast) begin
    lock_sync<={{lock_sync[0],locked}};
    request_sync<={{request_sync[0],request}};
    // Compare two cycles early, with a register between partial and full
    // equality; keep trigger arithmetic off the control CE path.
    switch_parts<={{index[8:6]==fire_index[8:6], index[5:3]==fire_index[5:3],
                    index[2:0]==fire_index[2:0]}};
    switch_now<=&switch_parts;
    capture_last<=(index=={SAMPLES-2});
    warm_mid<=(warm==32766);
    warm_done<=(warm==65534);
    settle_done<=(settle==1);
    lfsr<={{lfsr[30:0],lfsr[31]^lfsr[21]^lfsr[1]^lfsr[0]}};
    (* parallel_case *) case (1'b1)
      fast_state[BOOT]: if (!lock_sync[1]) warm<=0;
        else begin
          warm<=warm+1'b1;
          if (warm_mid) control<=3'b010;
          if (warm_done) fast_state<=4'b0010;
        end
      fast_state[IDLE]: begin
        index<=0;
        if (request_sync[1]!=acknowledge) begin
          win_seed<=lfsr; proposed<=next_control;
          trigger<=9'd128+{{2'b0,lfsr[6:0]}};
          fire_index<=9'd125+{{2'b0,lfsr[6:0]}};
          settle<=10'd256+{{2'b0,lfsr[17:10]}};
          checksum<=0; fast_state<=4'b0100;
        end
      end
      fast_state[SETTLE]: begin
        settle<=settle-1'b1;
        if (settle_done) fast_state<=4'b1000;
      end
      fast_state[CAPTURE]: begin
        memory[index]<=sample;
        checksum<=checksum^sample;
        if (switch_now) control<=proposed;
        index<=index+1'b1;
        if (capture_last) begin
          acknowledge<=request_sync[1]; fast_state<=4'b0010;
        end
      end
    endcase
  end

  reg [8:0] read_address=0;
  reg [47:0] read_data=0, word=0;
  always @(posedge clk_25mhz) read_data<=memory[read_address];
  function [7:0] hex(input [3:0] n);
    hex=(n<10) ? 8'h30+n : 8'h41+n-10;
  endfunction
  reg [31:0] event_sequence=0;
  reg [12:0] ci=0;
  reg [3:0] nibble=0;
  reg [7:0] ch;
  always @* begin
    if (ci==0) ch="D";
    else if (ci==1) ch="2";
    else if (ci==2) ch="{ident}";
    else if (ci<11) ch=hex(event_sequence[31-4*(ci-3) -: 4]);
    else if (ci<14) ch=hex({{3'b0,trigger}} >> (4*(13-ci)));
    else if (ci<22) ch=hex(win_seed[31-4*(ci-14) -: 4]);
    else if (ci<{PAYLOAD_END}) ch=hex(word[47:44]);
    else if (ci<{PAYLOAD_END+12}) ch=hex(checksum[47-4*(ci-{PAYLOAD_END}) -: 4]);
    else if (ci=={PAYLOAD_END+12}) ch=8'h0d;
    else ch=8'h0a;
  end
  localparam WAIT=0, LOAD0=1, LOAD1=2, LOAD2=3, SEND=4;
  reg [2:0] tx_state=WAIT;
  reg busy=0;
  reg [7:0] baud=0;
  reg [3:0] bitn=0;
  reg [9:0] shift=10'h3ff;
  assign ftdi_rxd=busy ? shift[0] : 1'b1;
  always @(posedge clk_25mhz) begin
    ack_sync<={{ack_sync[0],acknowledge}};
    case (tx_state)
      WAIT: if (ack_sync[1]==request) begin
        ci<=0; read_address<=0; nibble<=0; tx_state<=LOAD0;
      end
      LOAD0: tx_state<=LOAD1;
      LOAD1: tx_state<=LOAD2;
      LOAD2: begin word<=read_data; tx_state<=SEND; end
      SEND: if (!busy) begin
        shift<={{1'b1,ch,1'b0}}; bitn<=0; baud<=216; busy<=1;
      end else if (baud!=0) baud<=baud-1'b1;
      else begin
        baud<=216; shift<={{1'b1,shift[9:1]}}; bitn<=bitn+1'b1;
        if (bitn==9) begin
          busy<=0; ci<=ci+1'b1;
          if (ci>={PAYLOAD_START} && ci<{PAYLOAD_END}) begin
            word<=word<<4; nibble<=nibble+1'b1;
            if (nibble==11) begin
              nibble<=0;
              if (ci!={PAYLOAD_END-1}) begin
                read_address<=read_address+1'b1; tx_state<=LOAD0;
              end
            end
          end
          if (ci=={LINE_BYTES-1}) begin
            event_sequence<=event_sequence+1'b1; request<=~request; tx_state<=WAIT;
          end
        end
      end
    endcase
  end
endmodule
{OBSERVER}"""


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--variant", choices=MODES, default="dynamic")
    args = parser.parse_args()
    sys.stdout.write(generate(args.variant))


if __name__ == "__main__":
    main()
