"""Write hd06.v or hd06b.v: which clock enable, which reset and what GSR the
ALU54B output registers take (HD06).
Usage: python3 hd06_gen.py > hd06.v; python3 hd06_gen.py b > hd06b.v

The port lists of MULT18X18D and ALU54B are bit-per-port, so the file is
generated."""

ROW = 58
READ_C = "11'b01000111111"  # R = C: Z = 3, X and Y zero, a sum
import sys

# name, block X, second slice, controls (ce, rst), RESETMODE of the ALU, GSR,
# RESETMODE of its two MULT18
VARIANTS = {
    "": [
        ("ea", 13, False, "a", "SYNC", "DISABLED", "SYNC"),
        ("eb", 13, True, "a", "ASYNC", "DISABLED", "SYNC"),
        ("ec", 31, False, "b", "SYNC", "ENABLED", "SYNC"),
        ("ed", 31, True, "b", "ASYNC", "ENABLED", "SYNC"),
    ],
    "b": [
        ("ea", 13, False, "a", "ASYNC", "DISABLED", "SYNC"),
        ("eb", 13, True, "a", "SYNC", "DISABLED", "SYNC"),
        ("ec", 31, False, "b", "SYNC", "DISABLED", "ASYNC"),
        ("ed", 31, True, "b", "ASYNC", "DISABLED", "ASYNC"),
    ],
}
VARIANT = sys.argv[1] if len(sys.argv) > 1 else ""
ALUS = VARIANTS[VARIANT]


def bus(port, net, n, lo=0, plo=0):
    return ", ".join(f".{port}{k + plo}({net}[{k + lo}])" for k in range(n))


def controls(s):
    return ("CLK0(clk_25mhz), .CLK1(1'b0), .CLK2(1'b0), .CLK3(1'b0), "
            + ", ".join(f".CE{k}(ce{s}[{k}])" for k in range(4)) + ", "
            + ", ".join(f".RST{k}(rst{s}[{k}])" for k in range(4)))


def mult(bel, name, c_lo, s, mode):
    zeros = ", ".join(f".A{k}(1'b0), .B{k}(1'b0)" for k in range(18))
    return f"""  (* BEL="{bel}" *)
  MULT18X18D #(.REG_INPUTA_CLK("NONE"), .REG_INPUTB_CLK("NONE"), .REG_INPUTC_CLK("NONE"),
      .REG_PIPELINE_CLK("NONE"), .REG_OUTPUT_CLK("NONE"), .GSR("DISABLED"), .RESETMODE("{mode}"))
    {name}({zeros}, {bus("C", "c", 18, c_lo)},
      .SIGNEDA(1'b0), .SIGNEDB(1'b0), .SOURCEA(1'b0), .SOURCEB(1'b0), .{controls(s)},
      {bus("P", name + "_p", 36)}, {bus("ROA", name + "_roa", 18)}, {bus("ROB", name + "_rob", 18)},
      .SIGNEDP({name}_sp));
"""


print(f"""// HD06{VARIANT} slice: the clock enable, the reset and GSR of the ALU54B output
// register (D01, D05, D06). Generated by hd06_gen.py.
// Four ALU54B in two DSP blocks of row {ROW} (X 13 and 31), each with its two
// MULT18X18D (no registers) and R = C at every clock: OP = 01000111111, the C
// operand also on the MULT18 C ports. Output and flag registers on CLK0, the
// 25 MHz clock.
//   name  block  slice   CE0..3, RST0..3   RESETMODE  GSR       MULT18 RESETMODE
""" + "".join(f"//   {a[0]}    {a[1]}     {'second' if a[2] else 'first '}  ce{a[3]}, rst{a[3]}         {a[4]:<10} {a[5]:<9} {a[6]}\n" for a in ALUS) + f"""// A DSP block has four CE and four RST lines for both its slices (nextpnr
// puts one net on each), so the two ALUs of a block share theirs.
// cea, ceb (each bit high 3/4 of the time), rsta, rstb (each bit high 1/8) and
// gsr_n (low 1/32; it drives a GSR primitive) are fabric registers, new at
// every clock from disjoint fields of a 64-bit LFSR. C is another 64-bit
// LFSR, shifting every clock.
// Sample = {{cea[3:0], rsta[3:0], ceb[3:0], rstb[3:0], 000, gsr_n,
// c[50], c[30], c[20], c[0], then for ea, eb, ec, ed: R[50], R[30], R[20], R[0]}}
// at every 25 MHz edge, taken before the edge: one bit of each of the four
// groups of R. Line "M<2560 hex>": 256 samples, the first in the MSBs;
// windows follow one another, the first from the first clock.
module top(input clk_25mhz, output ftdi_rxd);
  reg [63:0] r = 64'h1D2CACE15EED0001;
  reg [63:0] d = 64'h0123456789ABCDEF;
  always @(posedge clk_25mhz) begin
    r <= {{r[62:0], r[63] ^ r[62] ^ r[60] ^ r[59]}};
    d <= {{d[62:0], d[63] ^ d[62] ^ d[60] ^ d[59]}};
  end
  wire [53:0] c = d[53:0];
  reg [3:0] cea = 4'hf, ceb = 4'hf, rsta = 0, rstb = 0;
  reg gsr_n = 1;
  always @(posedge clk_25mhz) begin
    cea <= {{r[1:0] != 0, r[3:2] != 0, r[5:4] != 0, r[7:6] != 0}};
    ceb <= {{r[9:8] != 0, r[11:10] != 0, r[13:12] != 0, r[15:14] != 0}};
    rsta <= {{r[18:16] == 0, r[21:19] == 0, r[24:22] == 0, r[27:25] == 0}};
    rstb <= {{r[30:28] == 0, r[33:31] == 0, r[36:34] == 0, r[39:37] == 0}};
    gsr_n <= r[44:40] != 0;
  end
  GSR gsr_inst(.GSR(gsr_n));
""")
for name, bx, second, s, mode, gsr, mult_mode in ALUS:
    x = bx + 4 * second
    m = [f"{name}_m0", f"{name}_m1"]
    print(f"""  wire [35:0] {m[0]}_p, {m[1]}_p;
  wire [17:0] {m[0]}_roa, {m[0]}_rob, {m[1]}_roa, {m[1]}_rob;
  wire {m[0]}_sp, {m[1]}_sp;
  wire [53:0] {name}_r;""")
    print(mult(f"X{x}/Y{ROW}/MULT18_{4 * second}", m[0], 0, s, mult_mode))
    print(mult(f"X{x + 1}/Y{ROW}/MULT18_{4 * second + 1}", m[1], 27, s, mult_mode))
    print(f"""  (* BEL="X{x + 3}/Y{ROW}/ALU54_{3 + 4 * second}" *)
  ALU54B #(.REG_OUTPUT0_CLK("CLK0"), .REG_OUTPUT1_CLK("CLK0"), .REG_FLAG_CLK("CLK0"),
      .GSR("{gsr}"), .RESETMODE("{mode}"))
    {name}({bus("A", m[0] + "_roa", 18)}, {bus("A", m[0] + "_rob", 18, 0, 18)},
      {bus("B", m[1] + "_roa", 18)}, {bus("B", m[1] + "_rob", 18, 0, 18)},
      {bus("MA", m[0] + "_p", 36)}, {bus("MB", m[1] + "_p", 36)},
      {bus("C", "c", 54)}, {", ".join(f".OP{k}(op[{k}])" for k in range(11))},
      .SIGNEDIA({m[0]}_sp), .SIGNEDIB({m[1]}_sp), .{controls(s)},
      {bus("R", name + "_r", 54)});
""")
picks = lambda v: f"{v}[50], {v}[30], {v}[20], {v}[0]"
print(f"""  wire [10:0] op = {READ_C};
  wire [39:0] s = {{cea, rsta, ceb, rstb, 3'b0, gsr_n, {picks("c")}, {", ".join(picks(a[0] + "_r") for a in ALUS)}}};

  reg [8:0] u = 0;
  reg [10239:0] rec = 0;
  localparam REC = 0, SEND = 1;
  reg state = REC;
  // UART: "M" 2560 hex CR LF, 115200 8N1.
  function [7:0] hex(input [3:0] v);
    hex = v < 10 ? 8'h30 + v : 8'h37 + v;
  endfunction
  reg [11:0] ci = 0;
  reg [7:0] ch;
  always @* begin
    if (ci == 0) ch = "M";
    else if (ci < 2561) ch = hex(rec[10239 - 4 * (ci - 1) -: 4]);
    else if (ci == 2561) ch = 8'h0d;
    else ch = 8'h0a;
  end
  reg tx = 1, busy = 0;
  reg [7:0] baud = 0;
  reg [3:0] bitn = 0;
  reg [9:0] shift = 10'h3ff;
  always @(posedge clk_25mhz)
    case (state)
      REC: begin
        rec <= {{rec[10199:0], s}};
        u <= u + 1;
        if (u == 255) begin state <= SEND; u <= 0; end
      end
      SEND:
        if (!busy) begin
          shift <= {{1'b1, ch, 1'b0}};
          busy <= 1; baud <= 0; bitn <= 0;
        end else if (baud == 216) begin
          baud <= 0;
          tx <= shift[0];
          shift <= {{1'b1, shift[9:1]}};
          bitn <= bitn + 1;
          if (bitn == 9) begin
            busy <= 0;
            if (ci == 2562) begin ci <= 0; state <= REC; end
            else ci <= ci + 1;
          end
        end else baud <= baud + 1;
    endcase
  assign ftdi_rxd = tx;
endmodule""")
