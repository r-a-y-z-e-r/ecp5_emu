"""Write hd05.v: the eight ALU54B of HD04 whose outputs are all registered
(HD05), for a record the emulator's fast mode can replay line by line: HD04
itself has ALUs whose unregistered R loops through their own operand.
Usage: python3 hd05_gen.py > hd05.v

The port lists of MULT18X18D and ALU54B are bit-per-port, so the file is
generated."""

MASKS = dict(
    A=dict(MCPAT="0x1555555555555A", MASKPAT="0x3FFFFFFFFFFFF0", MASK01="0x3FFFFFFFFFFF0F"),
    Z=dict(MCPAT="0x00000000000000", MASKPAT="0x00000000000000", MASK01="0x00000000000000"),
    O=dict(MCPAT="0x3FFFFFFFFFFFFF", MASKPAT="0x3FFFFFFFFFFFFF", MASK01="0x3FFFFFFFFFFFFF"),
)
RNDPAT = "0x0123456789ABC5"
PULSE, HIGH = "ce", "1'b1"
READ = "11'b01000011111"  # R = CIN >> 18: Z = 1, X and Y zero, a sum
# name, block X, operand set, OP, CIN source, (OUTPUT0, OUTPUT1, FLAG) clocks,
# CE0, masks. Every MULT18 has its C ports connected; CE1..3 are the pulse.
ALUS = [
    ("pa", 13, 1, "opa", None, ("CLK0", "CLK0", "CLK0"), PULSE, "A"),
    ("pb", 13, 2, READ, "pa", ("CLK0", "CLK0", "CLK0"), PULSE, "A"),
    ("qa", 22, 2, "opb", "pb", ("CLK0", "CLK0", "CLK0"), PULSE, "A"),
    ("qb", 22, 1, READ, "qa", ("CLK0", "CLK0", "CLK0"), PULSE, "A"),
    ("ra", 31, 1, READ, "qb", ("CLK0", "CLK0", "CLK0"), PULSE, "A"),
    ("rb", 31, 2, "opa", "ra", ("CLK0", "CLK0", "CLK0"), HIGH, "A"),
    ("sa", 49, 1, "opa", None, ("CLK0", "CLK0", "CLK0"), PULSE, "Z"),
    ("sb", 49, 2, "opa", "sa", ("CLK0", "CLK0", "CLK0"), PULSE, "O"),
]
ROW = 58


def bus(port, net, n, lo=0, plo=0):
    return ", ".join(f".{port}{k + plo}({net}[{k + lo}])" for k in range(n))


def controls(ce0):
    return (f".CLK0(clk_25mhz), .CLK1(1'b0), .CLK2(1'b0), .CLK3(1'b0), .CE0({ce0}), .CE1(ce), "
            f".CE2(ce), .CE3(ce), .RST0(1'b0), .RST1(1'b0), .RST2(1'b0), .RST3(1'b0)")


def mult(bel, name, a, b, sa, sb, c, cclk, ce):
    cports = f"{bus('C', c[0], 18, c[1])}, "
    return f"""  (* BEL="{bel}" *)
  MULT18X18D #(.REG_INPUTA_CLK("NONE"), .REG_INPUTB_CLK("NONE"), .REG_INPUTC_CLK("{cclk}"),
      .REG_PIPELINE_CLK("NONE"), .REG_OUTPUT_CLK("NONE"), .GSR("DISABLED"), .RESETMODE("SYNC"))
    {name}({bus("A", a, 18)}, {bus("B", b, 18)}, {cports}
      .SIGNEDA({sa}), .SIGNEDB({sb}), .SOURCEA(1'b0), .SOURCEB(1'b0), {controls(ce)},
      {bus("P", name + "_p", 36)}, {bus("ROA", name + "_roa", 18)}, {bus("ROB", name + "_rob", 18)},
      .SIGNEDP({name}_sp));
"""



print(f"""// HD05 slice: an ALU54B chain with every output registered, the part of HD04
// that repeats exactly. Generated by hd05_gen.py. Eight ALU54B in four DSP
// blocks of row {ROW}, each
// with its two MULT18X18D as in HD03 (the C operand also on the MULT18 C
// ports). The second ALU of a block (b) takes CIN and SIGNEDCIN from the
// first (a); block q follows block p, and r follows q, by the same cascade.
// Operand set 1 or 2 as listed; OP is one of
//   opa = n[12:2], four steps per opcode;
//   opb = opa * 1237 + 77 modulo 2048, the same opcodes in another order;
//   read = 01000011111: R = CIN >> 18, which shows the cascade's sign fill.
//   name  X   set  OP    outputs 0/1, flags    CE0    patterns
""" + "".join(f"//   {a[0]}    {a[1]:<3} {a[2]}    {'read' if a[3] == READ else a[3]:<5} {'/'.join(a[5]):<21} "
              f"{'pulse' if a[6] == PULSE else 'high':<6} {a[7]}\n" for a in ALUS) + f"""// Patterns A: MCPAT 1555555555555A, MASKPAT 3FFFFFFFFFFFF0, MASK01
// 3FFFFFFFFFFF0F; Z: all three zero; O: all three 3FFFFFFFFFFFFF. RNDPAT
// 0123456789ABC5 in all. CE1..3 are the pulse everywhere: one 25 MHz cycle per
// step, after the operands have settled.
// The first line, "I...", comes 2^24 cycles after configuration and before
// any pulse: the registers as configuration left them. Then lines
// "T<n:4><sg1:1><a0:5><b0:5><a1:5><b1:5><c:14>" for set 1, the same 35 digits
// for set 2, then for each ALU in the order above "<r:14><f:2>" with
// f = {{EQZ, EQZM, EQOM, EQPAT, EQPATB, OVER, UNDER, OVERUNDER}}. The LFSRs
// restart at n = 0, so the pass repeats.
module top(input clk_25mhz, output ftdi_rxd);
  reg [167:0] l1 = 168'h1;
  reg [166:0] l2 = 167'h1;
  reg [12:0] n = 0;
  wire [10:0] opa = n[12:2];
  wire [10:0] opb = opa * 11'd1237 + 11'd77;
  reg ce = 0;""")
for s, l in ((1, "l1"), (2, "l2")):
    print(f"""  wire [17:0] s{s}_a0 = {l}[17:0], s{s}_b0 = {l}[35:18], s{s}_a1 = {l}[53:36], s{s}_b1 = {l}[71:54];
  wire [53:0] s{s}_c = {l}[125:72];
  wire [3:0] s{s}_sg = {l}[129:126];""")
for k, (name, bx, s, op, cin, clocks, ce0, masks) in enumerate(ALUS):
    second = k % 2
    x = bx + 4 * second
    masks = MASKS[masks]
    m = [f"{name}_m0", f"{name}_m1"]
    print(f"""  wire [35:0] {m[0]}_p, {m[1]}_p;
  wire [17:0] {m[0]}_roa, {m[0]}_rob, {m[1]}_roa, {m[1]}_rob;
  wire {m[0]}_sp, {m[1]}_sp, {name}_sr;
  wire [53:0] {name}_r;
  wire [7:0] {name}_f;
  wire [10:0] {name}_op = {op};""")
    print(mult(f"X{x}/Y{ROW}/MULT18_{4 * second}", m[0], f"s{s}_a0", f"s{s}_b0", f"s{s}_sg[0]", f"s{s}_sg[1]",
               (f"s{s}_c", 0), "NONE", ce0))
    print(mult(f"X{x + 1}/Y{ROW}/MULT18_{4 * second + 1}", m[1], f"s{s}_a1", f"s{s}_b1", f"s{s}_sg[2]",
               f"s{s}_sg[3]", (f"s{s}_c", 27), "NONE", ce0))
    cinp = f"{bus('CIN', cin + '_r', 54)}, .SIGNEDCIN({cin}_sr)," if cin else ""
    print(f"""  (* BEL="X{x + 3}/Y{ROW}/ALU54_{3 + 4 * second}" *)
  ALU54B #(.REG_OUTPUT0_CLK("{clocks[0]}"), .REG_OUTPUT1_CLK("{clocks[1]}"), .REG_FLAG_CLK("{clocks[2]}"),
      .GSR("DISABLED"), .RESETMODE("SYNC"),
      .MCPAT("{masks['MCPAT']}"), .MASKPAT("{masks['MASKPAT']}"), .MASK01("{masks['MASK01']}"),
      .RNDPAT("{RNDPAT}"))
    {name}({bus("A", m[0] + "_roa", 18)}, {bus("A", m[0] + "_rob", 18, 0, 18)},
      {bus("B", m[1] + "_roa", 18)}, {bus("B", m[1] + "_rob", 18, 0, 18)},
      {bus("MA", m[0] + "_p", 36)}, {bus("MB", m[1] + "_p", 36)},
      {bus("C", f"s{s}_c", 54)}, {bus("OP", name + "_op", 11)}, {cinp}
      .SIGNEDIA({m[0]}_sp), .SIGNEDIB({m[1]}_sp), {controls(ce0)},
      {bus("R", name + "_r", 54)}, .SIGNEDR({name}_sr),
      .EQZ({name}_f[7]), .EQZM({name}_f[6]), .EQOM({name}_f[5]), .EQPAT({name}_f[4]),
      .EQPATB({name}_f[3]), .OVER({name}_f[2]), .UNDER({name}_f[1]), .OVERUNDER({name}_f[0]));
""")
sets = ", ".join(f"s{s}_sg, 2'b0, s{s}_a0, 2'b0, s{s}_b0, 2'b0, s{s}_a1, 2'b0, s{s}_b1, 2'b0, s{s}_c" for s in (1, 2))
outs = ", ".join(f"2'b0, {a[0]}_r, {a[0]}_f" for a in ALUS)
DIGITS = 4 + 35 * 2 + 16 * len(ALUS)
print(f"""  // The line: {DIGITS} hex digits after its letter.
  wire [{4 * DIGITS - 1}:0] line = {{3'b0, n, {sets}, {outs}}};
  reg [{4 * DIGITS - 1}:0] held = 0;
  function [7:0] hex(input [3:0] v);
    hex = v < 10 ? 8'h30 + v : 8'h37 + v;
  endfunction
  reg [8:0] ci = 0;
  reg [7:0] ch;
  reg first = 1;
  always @* begin
    if (ci == 0) ch = first ? "I" : "T";
    else if (ci < {DIGITS + 1}) ch = hex(held[{4 * DIGITS - 1} - 4 * (ci - 1) -: 4]);
    else if (ci == {DIGITS + 1}) ch = 8'h0d;
    else ch = 8'h0a;
  end
  localparam WAIT = 0, SHIFT = 1, SETTLE = 2, PULSE = 3, HOLD = 4, SEND = 5;
  reg [2:0] state = WAIT;
  reg [23:0] w = 0;
  reg [8:0] k = 0;
  reg tx = 1, busy = 0;
  reg [7:0] baud = 0;
  reg [3:0] bitn = 0;
  reg [9:0] shift = 10'h3ff;
  always @(posedge clk_25mhz) begin
    ce <= 0;
    case (state)
      WAIT: begin  // no pulse yet: the line shows the configured state
        w <= w + 1;
        if (&w) begin held <= line; state <= SEND; end
      end
      SHIFT: begin  // 168 shifts: every operand bit is new
        l1 <= {{l1[166:0], l1[167] ^ l1[165] ^ l1[152] ^ l1[150]}};
        l2 <= {{l2[165:0], l2[166] ^ l2[160]}};
        k <= k + 1;
        if (k == 167) begin k <= 0; state <= SETTLE; end
      end
      SETTLE: begin k <= k + 1; if (k == 7) begin k <= 0; state <= PULSE; end end
      PULSE: begin ce <= 1; state <= HOLD; end
      HOLD: begin k <= k + 1; if (k == 7) begin k <= 0; held <= line; state <= SEND; end end
      SEND:
        if (!busy) begin
          shift <= {{1'b1, ch, 1'b0}};
          busy <= 1; baud <= 0; bitn <= 0;
        end else if (baud == 216) begin
          baud <= 0;
          tx <= shift[0];
          shift <= {{1'b1, shift[9:1]}};
          bitn <= bitn + 1;
          if (bitn == 9) begin
            busy <= 0;
            if (ci == {DIGITS + 2}) begin
              ci <= 0;
              if (first) first <= 0;
              else begin
                n <= n + 1;
                if (&n) begin l1 <= 168'h1; l2 <= 167'h1; end
              end
              state <= SHIFT;
            end else ci <= ci + 1;
          end
        end else baud <= baud + 1;
      default: state <= WAIT;
    endcase
  end
  assign ftdi_rxd = tx;
endmodule""")
