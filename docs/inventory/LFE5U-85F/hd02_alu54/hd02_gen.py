"""Write hd02.v: the ALU54B opcode sweep (HD02). Usage: python3 hd02_gen.py
[VECTORS_LOG2 MCPAT MASKPAT MASK01 RNDPAT] > hd02.v

The port lists of MULT18X18D and ALU54B are bit-per-port, so the file is
generated."""
import sys

args = sys.argv[1:]
VLOG = int(args[0]) if args else 3
MCPAT, MASKPAT, MASK01, RNDPAT = (args[1:5] if len(args) >= 5 else
                                  ["0x1555555555555A", "0x3FFFFFFFFFFFF0",
                                   "0x3FFFFFFFFFFF0F", "0x0123456789ABC5"])


def bus(port, net, n, lo=0):
    return ", ".join(f".{port}{k}({net}[{k + lo}])" for k in range(n))


mult = lambda name, a, b, sa, sb, p, roa, rob, sp: f"""  MULT18X18D #(.REG_INPUTA_CLK("NONE"), .REG_INPUTB_CLK("NONE"), .REG_INPUTC_CLK("NONE"),
      .REG_PIPELINE_CLK("NONE"), .REG_OUTPUT_CLK("NONE"), .GSR("DISABLED"), .RESETMODE("SYNC"))
    {name}({bus("A", a, 18)}, {bus("B", b, 18)},
      .SIGNEDA({sa}), .SIGNEDB({sb}), .SOURCEA(1'b0), .SOURCEB(1'b0),
      .CLK0(clk_25mhz), .CLK1(1'b0), .CLK2(1'b0), .CLK3(1'b0),
      .CE0(ce), .CE1(ce), .CE2(ce), .CE3(ce), .RST0(1'b0), .RST1(1'b0), .RST2(1'b0), .RST3(1'b0),
      {bus("P", p, 36)}, {bus("ROA", roa, 18)}, {bus("ROB", rob, 18)}, .SIGNEDP({sp}));
"""

print(f"""// HD02 slice: the ALU54B operation table (D04). Generated by hd02_gen.py.
// Two MULT18X18D (every register bypassed) feed one ALU54B the way nextpnr
// needs it: A = {{ROB, ROA}} of m0, B = {{ROB, ROA}} of m1, MA = P of m0,
// MB = P of m1, SIGNEDIA/SIGNEDIB = their SIGNEDP. C and OP come from the
// fabric. Only the ALU's output and flag registers are on (CLK0, 25 MHz);
// CIN, CFB and SIGNEDCIN are not connected.
// Step n (0..{(2048 << VLOG) - 1}): OP = n[{10 + VLOG}:{VLOG}]; the operands are {130} fresh bits of a
// 168-bit LFSR: a0, b0, a1, b1 (18 bits each), c (54), and the signs
// sg = {{SIGNEDB1, SIGNEDA1, SIGNEDB0, SIGNEDA0}}. Everything holds still, then
// CE0..3 pulse together for one 25 MHz cycle: the output register captures
// once per step. {1 << VLOG} steps per opcode, one after another, so an operation
// that reads R back shows the previous line's R.
// Line "T<n:4 hex><sg:1><a0:5><b0:5><a1:5><b1:5><c:14><r:14><f:3>": r = R,
// f = {{EQZ, EQZM, EQOM, EQPAT, EQPATB, OVER, UNDER, OVERUNDER, 0}} after the
// pulse (SIGNEDR has no route to the fabric: it goes to the next ALU's
// SIGNEDCIN). The LFSR restarts at n = 0, so the pass repeats.
module top(input clk_25mhz, output ftdi_rxd);
  reg [167:0] l = 168'h1;
  reg [{10 + VLOG}:0] n = 0;
  wire [17:0] a0 = l[17:0], b0 = l[35:18], a1 = l[53:36], b1 = l[71:54];
  wire [53:0] c = l[125:72];
  wire [3:0] sg = l[129:126];
  wire [10:0] op = n[{10 + VLOG}:{VLOG}];
  reg ce = 0;
  wire [35:0] p0, p1;
  wire [17:0] roa0, rob0, roa1, rob1;
  wire sp0, sp1;
  wire [53:0] r;
  wire eqz, eqzm, eqom, eqpat, eqpatb, over, under, overunder;
""")
print(mult("m0", "a0", "b0", "sg[0]", "sg[1]", "p0", "roa0", "rob0", "sp0"))
print(mult("m1", "a1", "b1", "sg[2]", "sg[3]", "p1", "roa1", "rob1", "sp1"))
print(f"""  ALU54B #(.REG_OUTPUT0_CLK("CLK0"), .REG_OUTPUT1_CLK("CLK0"), .REG_FLAG_CLK("CLK0"),
      .GSR("DISABLED"), .RESETMODE("SYNC"),
      .MCPAT("{MCPAT}"), .MASKPAT("{MASKPAT}"), .MASK01("{MASK01}"), .RNDPAT("{RNDPAT}"))
    alu({bus("A", "roa0", 18)}, {", ".join(f".A{k + 18}(rob0[{k}])" for k in range(18))},
      {bus("B", "roa1", 18)}, {", ".join(f".B{k + 18}(rob1[{k}])" for k in range(18))},
      {bus("MA", "p0", 36)}, {bus("MB", "p1", 36)},
      {bus("C", "c", 54)}, {bus("OP", "op", 11)},
      .SIGNEDIA(sp0), .SIGNEDIB(sp1),
      .CLK0(clk_25mhz), .CLK1(1'b0), .CLK2(1'b0), .CLK3(1'b0),
      .CE0(ce), .CE1(ce), .CE2(ce), .CE3(ce), .RST0(1'b0), .RST1(1'b0), .RST2(1'b0), .RST3(1'b0),
      {bus("R", "r", 54)},
      .EQZ(eqz), .EQZM(eqzm), .EQOM(eqom), .EQPAT(eqpat), .EQPATB(eqpatb),
      .OVER(over), .UNDER(under), .OVERUNDER(overunder));

  // The line: 56 hex digits after "T".
  wire [223:0] line = {{{{{5 - VLOG}{{1'b0}}}}, n, sg, 2'b0, a0, 2'b0, b0, 2'b0, a1, 2'b0, b1, 2'b0, c, 2'b0, r,
                       3'b0, eqz, eqzm, eqom, eqpat, eqpatb, over, under, overunder, 1'b0}};
  reg [223:0] held = 0;
  function [7:0] hex(input [3:0] v);
    hex = v < 10 ? 8'h30 + v : 8'h37 + v;
  endfunction
  reg [5:0] ci = 0;
  reg [7:0] ch;
  always @* begin
    if (ci == 0) ch = "T";
    else if (ci < 57) ch = hex(held[223 - 4 * (ci - 1) -: 4]);
    else if (ci == 57) ch = 8'h0d;
    else ch = 8'h0a;
  end
  localparam SHIFT = 0, SETTLE = 1, PULSE = 2, HOLD = 3, SEND = 4;
  reg [2:0] state = SHIFT;
  reg [8:0] k = 0;
  reg tx = 1, busy = 0;
  reg [7:0] baud = 0;
  reg [3:0] bitn = 0;
  reg [9:0] shift = 10'h3ff;
  always @(posedge clk_25mhz) begin
    ce <= 0;
    case (state)
      SHIFT: begin  // 168 shifts: every operand bit is new
        l <= {{l[166:0], l[167] ^ l[165] ^ l[152] ^ l[150]}};
        k <= k + 1;
        if (k == 167) begin k <= 0; state <= SETTLE; end
      end
      SETTLE: begin k <= k + 1; if (k == 7) begin k <= 0; state <= PULSE; end end
      PULSE: begin ce <= 1; state <= HOLD; end
      HOLD: begin k <= k + 1; if (k == 7) begin k <= 0; held <= line; state <= SEND; end end
      SEND:
        if (!busy) begin
          shift <= {{1'b1, ch, 1'b0}};
          busy <= 1; baud <= 0; bitn <= 0;
        end else if (baud == 216) begin
          baud <= 0;
          tx <= shift[0];
          shift <= {{1'b1, shift[9:1]}};
          bitn <= bitn + 1;
          if (bitn == 9) begin
            busy <= 0;
            if (ci == 58) begin
              ci <= 0;
              n <= n + 1;
              if (&n) l <= 168'h1;
              state <= SHIFT;
            end else ci <= ci + 1;
          end
        end else baud <= baud + 1;
      default: state <= SHIFT;
    endcase
  end
  assign ftdi_rxd = tx;
endmodule""")
