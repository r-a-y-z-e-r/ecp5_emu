"""Generate HY01 SGSR slice probes. stdout: Verilog; optional positional 's'.

All inferred FFs must receive GSR=DISABLED after synth_ecp5, then only the six
named probe_* cells receive ENABLED. build.py implements and checks this.
"""
import argparse
import sys

SAMPLES = 512
PREFIX = "Y1"
PAYLOAD_START = 19  # Y1 + variant + sequence(8) + LFSR seed(8)
PAYLOAD_END = PAYLOAD_START + 4 * SAMPLES
LINE_BYTES = PAYLOAD_END + 4 + 2


def generate(startup=False):
    probes = []
    for group, (clock, mux) in enumerate((("clk_25mhz", "CLK"),
                                         ("clk_25mhz", "INV"), ("other", "CLK"))):
        for regset in range(2):
            name = "set" if regset else "reset"
            probes.append(f'''  (* keep=1, hy01_probe=1 *)
  TRELLIS_FF #(.GSR("ENABLED"), .REGSET("{name.upper()}"),
    .CLKMUX("{mux}"), .CEMUX("1"), .LSRMUX("LSR"), .SRMODE("ASYNC"))
    probe_{group}_{name}(.CLK({clock}), .CE(1'b1), .LSR(1'b0),
      .DI(phase[{group}]), .Q(q[{2*group+regset}]));''')
    return r'''// Generated by hy01_gen.py. See README.md for sampling and build policy.
module top(input clk_25mhz, output ftdi_rxd);
  wire fast, other, locked;
  // 25 -> 600 MHz VCO -> 100 MHz observer and 600/17 MHz other clock.
  // Different-frequency PLL output, not an independent oscillator.
  (* FREQUENCY_PIN_CLKI="25", FREQUENCY_PIN_CLKOP="100",
     FREQUENCY_PIN_CLKOS="35.294118", ICP_CURRENT="12", LPF_RESISTOR="8",
     MFG_ENABLE_FILTEROPAMP="1", MFG_GMCREF_SEL="2" *)
  EHXPLLL #(.PLLRST_ENA("DISABLED"), .INTFB_WAKE("DISABLED"),
    .STDBY_ENABLE("DISABLED"), .DPHASE_SOURCE("DISABLED"),
    .OUTDIVIDER_MUXA("DIVA"), .OUTDIVIDER_MUXB("DIVB"),
    .OUTDIVIDER_MUXC("DIVC"), .OUTDIVIDER_MUXD("DIVD"),
    .CLKI_DIV(1), .CLKFB_DIV(4), .FEEDBK_PATH("CLKOP"),
    .CLKOP_ENABLE("ENABLED"), .CLKOP_DIV(6), .CLKOP_CPHASE(2), .CLKOP_FPHASE(0),
    .CLKOS_ENABLE("ENABLED"), .CLKOS_DIV(17), .CLKOS_CPHASE(8), .CLKOS_FPHASE(0))
  pll(.CLKI(clk_25mhz), .CLKFB(fast), .CLKOP(fast), .CLKOS(other),
    .RST(1'b0), .STDBY(1'b0), .PHASESEL0(1'b0), .PHASESEL1(1'b0),
    .PHASEDIR(1'b1), .PHASESTEP(1'b1), .PHASELOADREG(1'b1),
    .PLLWAKESYNC(1'b0), .ENCLKOP(1'b0), .LOCK(locked));

  // Each marker changes once per edge of its probe clock. The probe sees
  // the OLD marker as D, so normal Q at that edge is ~NEW marker.
  (* keep=1 *) reg [2:0] phase=0;
  always @(posedge clk_25mhz) phase[0]<=~phase[0];
  always @(negedge clk_25mhz) phase[1]<=~phase[1];
  always @(posedge other) phase[2]<=~phase[2];
  wire [5:0] q;
@PROBES@
  reg gsr_n=1;
  SGSR u(.GSR(gsr_n), .CLK(clk_25mhz));

  // Identical two-stage observation of GSR_N, D markers, Q, and PLL LOCK.
  // Q and its marker can resolve into adjacent bins: analysis retains this
  // uncertainty, and never treats a naturally equal REGSET as a reset edge.
  (* async_reg="true" *) reg [10:0] obs1=0, obs2=0;
  always @(posedge fast) begin
    obs1<={locked,gsr_n,phase,q}; obs2<=obs1;
  end
  wire [15:0] sample={obs2,5'b0};
  reg request=1, acknowledge=0;
  (* async_reg="true" *) reg [1:0] req_sync=0, ack_sync=0;
  reg [15:0] memory [0:511];
  reg [31:0] lfsr=32'h48593031, win_seed=0;
  reg [8:0] index=0;
  reg [7:0] onset=128;
  reg [8:0] finish=208;
  reg [15:0] checksum=0;
  reg [11:0] warm=0;
  // No FSM extraction: preserve initialized configuration capture state.
  (* fsm_encoding="none" *) reg [1:0] capture_state=@INITIAL@;
  localparam BOOT=0, IDLE=1, CAPTURE=2;
  function [6:0] width_ticks(input [2:0] choice);
    case(choice)
      0: width_ticks=4; 1: width_ticks=8; 2: width_ticks=12;
      3: width_ticks=20; default: width_ticks=80;
    endcase
  endfunction
  always @(posedge fast) begin
    req_sync<={req_sync[0],request};
    lfsr<={lfsr[30:0],lfsr[31]^lfsr[21]^lfsr[1]^lfsr[0]};
    case(capture_state)
      BOOT: if (!obs2[10]) warm<=0;
        else begin warm<=warm+1'b1; if (&warm) capture_state<=IDLE; end
      IDLE: if (req_sync[1]!=acknowledge) begin
        win_seed<=lfsr; index<=0; checksum<=0;
        onset<=8'd128+{2'b0,lfsr[5:0]};
        finish<=9'd128+{3'b0,lfsr[5:0]}+width_ticks(lfsr[8:6]);
        capture_state<=CAPTURE;
      end
      CAPTURE: begin
        // s begins here on the first fast edge, without waiting for LOCK.
        if (index==0) win_seed<=lfsr;
        memory[index]<=sample; checksum<=checksum^sample;
        if (index=={1'b0,onset}) gsr_n<=0;
        if (index==finish) gsr_n<=1;
        index<=index+1'b1;
        if (index==511) begin acknowledge<=req_sync[1]; capture_state<=IDLE; end
      end
    endcase
  end

  // Dual-clock EBR, bundled-data handshake. RAM/header/checksum remain
  // unchanged throughout UART transmission. No next request until LF ends.
  reg [8:0] read_address=0;
  reg [15:0] read_data=0, word=0;
  always @(posedge clk_25mhz) read_data<=memory[read_address];
  function [7:0] hex(input [3:0] n);
    hex=n<10 ? 8'h30+n : 8'h37+n;
  endfunction
  reg [31:0] sequence_number=0;
  reg [11:0] ci=0;
  reg [1:0] nibble=0;
  reg [7:0] ch;
  always @* begin
    if (ci==0) ch="Y";
    else if (ci==1) ch="1";
    else if (ci==2) ch="@VARIANT@";
    else if (ci<11) ch=hex(sequence_number >> (4*(10-ci)));
    else if (ci<19) ch=hex(win_seed >> (4*(18-ci)));
    else if (ci<2067) ch=hex(word[15:12]);
    else if (ci<2071) ch=hex(checksum >> (4*(2070-ci)));
    else if (ci==2071) ch=8'h0d;
    else ch=8'h0a;
  end
  localparam WAIT=0, LOAD0=1, LOAD1=2, LOAD2=3, SEND=4;
  reg [2:0] tx_state=WAIT;
  reg busy=0;
  reg [7:0] baud=0;
  reg [3:0] bitn=0;
  reg [9:0] shift=10'h3ff;
  assign ftdi_rxd=busy ? shift[0] : 1'b1;
  always @(posedge clk_25mhz) begin
    ack_sync<={ack_sync[0],acknowledge};
    case(tx_state)
      WAIT: if (ack_sync[1]==request) begin
        ci<=0; read_address<=0; nibble<=0; tx_state<=LOAD0;
      end
      LOAD0: tx_state<=LOAD1;
      LOAD1: tx_state<=LOAD2;
      LOAD2: begin word<=read_data; tx_state<=SEND; end
      SEND: if (!busy) begin
        shift<={1'b1,ch,1'b0}; bitn<=0; baud<=216; busy<=1;
      end else if (baud!=0) baud<=baud-1'b1;
      else begin
        baud<=216; shift<={1'b1,shift[9:1]}; bitn<=bitn+1'b1;
        if (bitn==9) begin
          busy<=0; ci<=ci+1'b1;
          if (ci>=19 && ci<2067) begin
            word<=word<<4; nibble<=nibble+1'b1;
            if (nibble==3 && ci!=2066) begin
              read_address<=read_address+1'b1; tx_state<=LOAD0;
            end
          end
          if (ci==2072) begin
            sequence_number<=sequence_number+1'b1;
            @NEXT@
            tx_state<=WAIT;
          end
        end
      end
    endcase
  end
endmodule
'''.replace('@PROBES@', '\n'.join(probes)).replace(
        '@INITIAL@', "2'd2" if startup else "2'd0").replace(
        '@VARIANT@', 'S' if startup else 'R').replace(
        '@NEXT@', '// Resend the first capture.' if startup else 'request<=~request;')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('variant', nargs='?', choices=['s'])
    args = parser.parse_args()
    sys.stdout.write(generate(args.variant == 's'))
