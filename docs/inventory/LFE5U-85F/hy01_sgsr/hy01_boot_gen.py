"""Generate hy01b (SGSR tied high) or hy01c (no user GSR) startup counters.
Usage: python3 -B hy01_boot_gen.py b > /private/tmp/hy01b.v
The counter FFs run from configuration, on the pin clock, without a PLL.
"""
import argparse
import sys


def counter_names(enabled):
    return {f'count_{"a" if enabled else "b"}_{edge}_{bit:02d}'
            for edge in ('r', 'f') for bit in range(16)}


def generate(variant='b'):
    if variant not in ('b', 'c'):
        raise ValueError('variant must be b or c')
    counters = []
    for edge in ('r', 'f'):
        mux = 'CLK' if edge == 'r' else 'INV'
        for bank in ('a', 'b'):
            signal = f'{bank}_{edge}'
            counters.append(f'  wire [15:0] {signal};\n  wire [15:0] {signal}_next={signal}+16\'d1;')
            for bit in range(16):
                gsr = 'ENABLED' if bank == 'a' else 'DISABLED'
                counters.append(f'''  (* keep=1, hy01_counter="{signal}" *)
  TRELLIS_FF #(.GSR("{gsr}"), .REGSET("RESET"), .CLKMUX("{mux}"),
    .CEMUX("1"), .LSRMUX("LSR"), .SRMODE("ASYNC"))
  count_{signal}_{bit:02d}(.CLK(clk_25mhz), .CE(1'b1), .LSR(1'b0),
    .DI({signal}_next[{bit}]), .Q({signal}[{bit}]));''')
    return r'''// Generated by hy01_boot_gen.py. No PLL; all four counters free-run.
module top(input clk_25mhz, output ftdi_rxd);
@SGSR@
@COUNTERS@
  // Every support FF below is GSR-disabled by build_boot.py.
  reg [19:0] delay=0;
  reg request=0, acknowledge=0;
  reg [15:0] ar_hold=0, br_hold=0, af_hold=0, bf_hold=0;
  // Snapshot both members of each pair on the SAME edge of their own clock.
  // The falling-edge handshake has a timed half cycle in either direction.
  always @(negedge clk_25mhz) begin
    if (request!=acknowledge) begin
      af_hold<=a_f; bf_hold<=b_f; acknowledge<=request;
    end
  end
  wire [15:0] delta_r=br_hold-ar_hold, delta_f=bf_hold-af_hold;
  wire [95:0] snapshot={ar_hold,br_hold,delta_r,af_hold,bf_hold,delta_f};
  wire [15:0] snapshot_xor=ar_hold^br_hold^delta_r^af_hold^bf_hold^delta_f;
  reg [95:0] payload=0, word=0;
  reg [15:0] checksum=0;
  (* fsm_encoding="none" *) reg [1:0] state=0;
  reg [5:0] ci=0;
  reg busy=0;
  reg [7:0] baud=0;
  reg [3:0] bitn=0;
  reg [9:0] shift=10'h3ff;
  assign ftdi_rxd=busy ? shift[0] : 1'b1;
  function [7:0] hex(input [3:0] n);
    hex=n<10 ? 8'h30+n : 8'h37+n;
  endfunction
  reg [7:0] ch;
  always @* begin
    if (ci==0) ch="Y";
    else if (ci==1) ch="1";
    else if (ci==2) ch="@VARIANT@";
    else if (ci<27) ch=hex(word[95:92]);
    else if (ci<31) ch=hex(checksum >> (4*(30-ci)));
    else if (ci==31) ch=8'h0d;
    else ch=8'h0a;
  end
  always @(posedge clk_25mhz) begin
    case(state)
      0: begin
        delay<=delay+1'b1;
        if (&delay) begin
          ar_hold<=a_r; br_hold<=b_r; request<=1; state<=1;
        end
      end
      1: if (acknowledge==request) begin
        payload<=snapshot; word<=snapshot; checksum<=snapshot_xor; state<=2;
      end
      2: if (!busy) begin
        shift<={1'b1,ch,1'b0}; bitn<=0; baud<=216; busy<=1;
      end else if (baud!=0) baud<=baud-1'b1;
      else begin
        baud<=216; shift<={1'b1,shift[9:1]}; bitn<=bitn+1'b1;
        if (bitn==9) begin
          busy<=0; ci<=ci+1'b1;
          if (ci>=3 && ci<27) word<=word<<4;
          if (ci==32) begin ci<=0; word<=payload; end
        end
      end
    endcase
  end
endmodule
'''.replace('@SGSR@', '  (* keep=1 *) SGSR u(.GSR(1\'b1), .CLK(clk_25mhz));'
            if variant == 'b' else '  // Control: no SGSR or GSR primitive.').replace(
                '@COUNTERS@', '\n'.join(counters)).replace('@VARIANT@', variant.upper())


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('variant', choices=('b', 'c'))
    args = p.parse_args()
    sys.stdout.write(generate(args.variant))
