"""Write hd03.v: six ALU54B in three adjacent DSP blocks (HD03): the cascade
input CIN, the feedback CFB, the C operand's paths, the flags and which CE
the registers take. Usage: python3 hd03_gen.py > hd03.v

The port lists of MULT18X18D and ALU54B are bit-per-port, so the file is
generated."""

POL_A = dict(MCPAT="0x1555555555555A", MASKPAT="0x3FFFFFFFFFFFF0", MASK01="0x3FFFFFFFFFFF0F")
POL_B = dict(MCPAT="0x1555555555555A", MASKPAT="0x0000000000000F", MASK01="0x000000000000F0")
RNDPAT = "0x0123456789ABC5"
PULSE, HIGH = "ce", "1'b1"
# name, operand set, CIN source, CFB source, MULT C ports, MULT INPUTC clock,
# ALU INPUTC clock, flag clock, (CE0, CE1..3), masks
ALUS = [
    ("a0", 1, None, "a0", True, "NONE", "NONE", "NONE", (PULSE, PULSE), POL_A),
    ("b0", 2, "a0", None, True, "CLK0", "NONE", "NONE", (PULSE, PULSE), POL_B),
    ("a1", 1, "b0", None, False, "NONE", "CLK0", "CLK0", (PULSE, PULSE), POL_A),
    ("b1", 2, "a1", "b1", True, "NONE", "NONE", "CLK0", (PULSE, HIGH), POL_B),
    ("a2", 1, "b1", None, True, "NONE", "NONE", "CLK0", (HIGH, PULSE), POL_A),
    ("b2", 2, "a2", None, False, "NONE", "NONE", "NONE", (PULSE, PULSE), POL_B),
]
BLOCK_X = [13, 22, 31]
ROW = 58


def bus(port, net, n, lo=0, plo=0):
    return ", ".join(f".{port}{k + plo}({net}[{k + lo}])" for k in range(n))


def controls(ce):
    return (f".CLK0(clk_25mhz), .CLK1(1'b0), .CLK2(1'b0), .CLK3(1'b0), .CE0({ce[0]}), .CE1({ce[1]}), "
            f".CE2({ce[1]}), .CE3({ce[1]}), .RST0(1'b0), .RST1(1'b0), .RST2(1'b0), .RST3(1'b0)")


def mult(bel, name, a, b, sa, sb, c, cclk, ce):
    cports = f"{bus('C', c[0], 18, c[1])}, " if c else ""
    return f"""  (* BEL="{bel}" *)
  MULT18X18D #(.REG_INPUTA_CLK("NONE"), .REG_INPUTB_CLK("NONE"), .REG_INPUTC_CLK("{cclk}"),
      .REG_PIPELINE_CLK("NONE"), .REG_OUTPUT_CLK("NONE"), .GSR("DISABLED"), .RESETMODE("SYNC"))
    {name}({bus("A", a, 18)}, {bus("B", b, 18)}, {cports}
      .SIGNEDA({sa}), .SIGNEDB({sb}), .SOURCEA(1'b0), .SOURCEB(1'b0), {controls(ce)},
      {bus("P", name + "_p", 36)}, {bus("ROA", name + "_roa", 18)}, {bus("ROB", name + "_rob", 18)},
      .SIGNEDP({name}_sp));
"""


print(f"""// HD03 slice: the ALU54B inputs the HD02 sweep left open. Generated by
// hd03_gen.py. Six ALU54B in three adjacent DSP blocks (X {BLOCK_X}, row {ROW}),
// each with its two MULT18X18D as in HD02, chained by the dedicated cascade:
// CIN and SIGNEDCIN of each come from R and SIGNEDR of the one before.
// The first ALU of a block (a0, a1, a2) takes operand set 1, the second
// (b0, b1, b2) set 2: a0, b0, a1, b1, c and four signs from two LFSRs of
// their own. All six take the same OP = n[12:2]; four steps per opcode.
//   name  CFB    C operand                          flags      CE0 / CE1..3   masks
//   a0    own R  also on the MULT18 C ports         unregistered  pulse / pulse  A
//   b0    -      MULT18 C ports, REG_INPUTC_CLK=CLK0  unregistered  pulse / pulse  B
//   a1    -      ALU REG_INPUTC0/1_CLK=CLK0           registered    pulse / pulse  A
//   b1    own R  also on the MULT18 C ports         registered    pulse / high   B
//   a2    -      also on the MULT18 C ports         registered    high / pulse   A
//   b2    -      ALU pins only (as HD02)            unregistered  pulse / pulse  B
// Masks A: MASKPAT 3FFFFFFFFFFFF0, MASK01 3FFFFFFFFFFF0F; B: 0000000000000F and
// 000000000000F0. MCPAT 1555555555555A, RNDPAT 0123456789ABC5 in all.
// "pulse" is one 25 MHz cycle per step, after the operands have settled.
// Line "T<n:4><sg1:1><a0:5><b0:5><a1:5><b1:5><c:14>" for set 1, the same 35
// digits for set 2, then for a0, b0, a1, b1, a2, b2 each "<r:14><f:2>" with
// f = {{EQZ, EQZM, EQOM, EQPAT, EQPATB, OVER, UNDER, OVERUNDER}}. The LFSRs
// restart at n = 0, so the pass repeats.
module top(input clk_25mhz, output ftdi_rxd);
  reg [167:0] l1 = 168'h1;
  reg [166:0] l2 = 167'h1;
  reg [12:0] n = 0;
  wire [10:0] op = n[12:2];
  reg ce = 0;""")
for s, l in ((1, "l1"), (2, "l2")):
    print(f"""  wire [17:0] s{s}_a0 = {l}[17:0], s{s}_b0 = {l}[35:18], s{s}_a1 = {l}[53:36], s{s}_b1 = {l}[71:54];
  wire [53:0] s{s}_c = {l}[125:72];
  wire [3:0] s{s}_sg = {l}[129:126];""")
for k, (name, s, cin, cfb, mc, mclk, aclk, fclk, ce, masks) in enumerate(ALUS):
    x = BLOCK_X[k // 2] + 4 * (k % 2)
    m = [f"{name}_m0", f"{name}_m1"]
    print(f"""  wire [35:0] {m[0]}_p, {m[1]}_p;
  wire [17:0] {m[0]}_roa, {m[0]}_rob, {m[1]}_roa, {m[1]}_rob;
  wire {m[0]}_sp, {m[1]}_sp, {name}_sr;
  wire [53:0] {name}_r;
  wire [7:0] {name}_f;""")
    print(mult(f"X{x}/Y{ROW}/MULT18_{4 * (k % 2)}", m[0], f"s{s}_a0", f"s{s}_b0", f"s{s}_sg[0]", f"s{s}_sg[1]",
               (f"s{s}_c", 0) if mc else None, mclk, ce))
    print(mult(f"X{x + 1}/Y{ROW}/MULT18_{4 * (k % 2) + 1}", m[1], f"s{s}_a1", f"s{s}_b1", f"s{s}_sg[2]",
               f"s{s}_sg[3]", (f"s{s}_c", 27) if mc else None, mclk, ce))
    cinp = f"{bus('CIN', cin + '_r', 54)}, .SIGNEDCIN({cin}_sr)," if cin else ""
    cfbp = f"{bus('CFB', cfb + '_r', 54)}," if cfb else ""
    print(f"""  (* BEL="X{x + 3}/Y{ROW}/ALU54_{3 + 4 * (k % 2)}" *)
  ALU54B #(.REG_OUTPUT0_CLK("CLK0"), .REG_OUTPUT1_CLK("CLK0"), .REG_FLAG_CLK("{fclk}"),
      .REG_INPUTC0_CLK("{aclk}"), .REG_INPUTC1_CLK("{aclk}"), .GSR("DISABLED"), .RESETMODE("SYNC"),
      .MCPAT("{masks['MCPAT']}"), .MASKPAT("{masks['MASKPAT']}"), .MASK01("{masks['MASK01']}"),
      .RNDPAT("{RNDPAT}"))
    {name}({bus("A", m[0] + "_roa", 18)}, {bus("A", m[0] + "_rob", 18, 0, 18)},
      {bus("B", m[1] + "_roa", 18)}, {bus("B", m[1] + "_rob", 18, 0, 18)},
      {bus("MA", m[0] + "_p", 36)}, {bus("MB", m[1] + "_p", 36)},
      {bus("C", f"s{s}_c", 54)}, {bus("OP", "op", 11)}, {cinp} {cfbp}
      .SIGNEDIA({m[0]}_sp), .SIGNEDIB({m[1]}_sp), {controls(ce)},
      {bus("R", name + "_r", 54)}, .SIGNEDR({name}_sr),
      .EQZ({name}_f[7]), .EQZM({name}_f[6]), .EQOM({name}_f[5]), .EQPAT({name}_f[4]),
      .EQPATB({name}_f[3]), .OVER({name}_f[2]), .UNDER({name}_f[1]), .OVERUNDER({name}_f[0]));
""")
sets = ", ".join(f"s{s}_sg, 2'b0, s{s}_a0, 2'b0, s{s}_b0, 2'b0, s{s}_a1, 2'b0, s{s}_b1, 2'b0, s{s}_c" for s in (1, 2))
outs = ", ".join(f"2'b0, {a[0]}_r, {a[0]}_f" for a in ALUS)
DIGITS = 4 + 35 * 2 + 16 * len(ALUS)
print(f"""  // The line: {DIGITS} hex digits after "T".
  wire [{4 * DIGITS - 1}:0] line = {{3'b0, n, {sets}, {outs}}};
  reg [{4 * DIGITS - 1}:0] held = 0;
  function [7:0] hex(input [3:0] v);
    hex = v < 10 ? 8'h30 + v : 8'h37 + v;
  endfunction
  reg [7:0] ci = 0;
  reg [7:0] ch;
  always @* begin
    if (ci == 0) ch = "T";
    else if (ci < {DIGITS + 1}) ch = hex(held[{4 * DIGITS - 1} - 4 * (ci - 1) -: 4]);
    else if (ci == {DIGITS + 1}) ch = 8'h0d;
    else ch = 8'h0a;
  end
  localparam SHIFT = 0, SETTLE = 1, PULSE = 2, HOLD = 3, SEND = 4;
  reg [2:0] state = SHIFT;
  reg [8:0] k = 0;
  reg tx = 1, busy = 0;
  reg [7:0] baud = 0;
  reg [3:0] bitn = 0;
  reg [9:0] shift = 10'h3ff;
  always @(posedge clk_25mhz) begin
    ce <= 0;
    case (state)
      SHIFT: begin  // 168 shifts: every operand bit is new
        l1 <= {{l1[166:0], l1[167] ^ l1[165] ^ l1[152] ^ l1[150]}};
        l2 <= {{l2[165:0], l2[166] ^ l2[160]}};
        k <= k + 1;
        if (k == 167) begin k <= 0; state <= SETTLE; end
      end
      SETTLE: begin k <= k + 1; if (k == 7) begin k <= 0; state <= PULSE; end end
      PULSE: begin ce <= 1; state <= HOLD; end
      HOLD: begin k <= k + 1; if (k == 7) begin k <= 0; held <= line; state <= SEND; end end
      SEND:
        if (!busy) begin
          shift <= {{1'b1, ch, 1'b0}};
          busy <= 1; baud <= 0; bitn <= 0;
        end else if (baud == 216) begin
          baud <= 0;
          tx <= shift[0];
          shift <= {{1'b1, shift[9:1]}};
          bitn <= bitn + 1;
          if (bitn == 9) begin
            busy <= 0;
            if (ci == {DIGITS + 2}) begin
              ci <= 0;
              n <= n + 1;
              if (&n) begin l1 <= 168'h1; l2 <= 167'h1; end
              state <= SHIFT;
            end else ci <= ci + 1;
          end
        end else baud <= baud + 1;
      default: state <= SHIFT;
    endcase
  end
  assign ftdi_rxd = tx;
endmodule""")
