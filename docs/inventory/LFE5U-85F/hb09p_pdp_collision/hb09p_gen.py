"""HB09P: raw PDP36 collisions in the profiles inferred by Yosys.

python3 hb09p_gen.py [s] > hb09p[s].v
Uses HB09's INITVAL packing, LFSR, recorder timing and UART protocol. No board IO.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "hb09_ebr_collision"))
from hb09_gen import MASK64, SEED, LFSR_STEPS, lfsr_step, _initval_params  # noqa: E402

# All eight use DATA_WIDTH_A/B=36, NOREG, NORMAL, ASYNC reset/release.
# The shallow profiles differ in address pins tied low; width 32 leaves four
# unused data pins. Drive those don't-care pins to zero and record logical bits.
EBRS = [(f"p{w}_{d}", w, d) for w in (32, 36) for d in (64, 128, 256, 512)]
SAMPLES = 64
SAMPLE_BITS = sum(w for _, w, _ in EBRS)  # 272, no padding
HEX_SAMPLES = SAMPLES * SAMPLE_BITS // 4
LINE_LEN = 1 + 16 + HEX_SAMPLES


def traffic_fields(state, depth):
    """Four hot words span both ends of the inferred address space.

    P(read address == write address) = 5/8; P(collision) = 5/16.
    All four nine-bit masks are either enabled together or disabled together.
    """
    wa = state & 3
    ra = wa if (state >> 5) & 1 else (state >> 2) & 3

    def word(index):
        return (depth - 2 if index & 2 else 0) | (index & 1)

    return word(wa), word(ra), (state >> 4) & 1, (state >> 6) & ((1 << 36) - 1)


def init_words(name, width):
    state = (0x4842303950 + [e[0] for e in EBRS].index(name) * 0x9E3779B97F4A7C15) & MASK64
    words = []
    for _ in range(512):
        state = (state * 6364136223846793005 + 1442695040888963407) & MASK64
        words.append((state >> 20) & ((1 << width) - 1))
    return words


def ebr(name, width, depth):
    # HB01 measured this raw DP16KD wrapper's DO order. Instantiating the
    # public PDPW16KD instead would invoke nextpnr's reversed DO packing.
    words9 = [(word >> (9 * lane)) & 511 for word in init_words(name, width) for lane in range(4)]
    params = [
        ".DATA_WIDTH_A(36)", ".DATA_WIDTH_B(36)",
        '.REGMODE_A("NOREG")', '.REGMODE_B("NOREG")',
        '.WRITEMODE_A("NORMAL")', '.WRITEMODE_B("NORMAL")',
        '.RESETMODE("ASYNC")', '.ASYNC_RESET_RELEASE("ASYNC")',
        '.GSR("DISABLED")', '.CSDECODE_A("0b000")', '.CSDECODE_B("0b000")',
    ] + _initval_params(words9)
    ports = [
        ".CLKA(clk_25mhz)", ".CLKB(clk_25mhz)",
        ".CEA(1'b1)", ".CEB(1'b1)", ".OCEA(1'b0)", ".OCEB(1'b1)",
        ".WEA(1'b1)", ".WEB(1'b0)", ".RSTA(1'b0)", ".RSTB(1'b0)",
    ]
    ports += [f".CS{side}{i}(1'b0)" for side in "AB" for i in range(3)]
    for side, addr in (("A", "wa"), ("B", "ra")):
        for i in range(14):
            signal = "we" if side == "A" and i < 4 else "1'b0"
            if 5 <= i < 5 + (depth - 1).bit_length():
                # Hot selectors 0,1,2,3 map to 0,1,depth-2,depth-1.
                signal = f"{addr}[0]" if i == 5 else f"{addr}[1]"
            ports.append(f".AD{side}{i}({signal})")
        for i in range(18):
            bit = i + (18 if side == "B" else 0)
            signal = f"data[{bit}]" if bit < width else "1'b0"
            ports += [f".DI{side}{i}({signal})", f".DO{side}{i}({name}_q[{bit}])"]
    return (f"  wire [35:0] {name}_q;\n  DP16KD #(\n    " + ",\n    ".join(params)
            + f"\n  ) {name} (\n    " + ",\n    ".join(ports) + ");\n")


def generate(once=False):
    total = SAMPLES * SAMPLE_BITS
    last = 17 + HEX_SAMPLES + 1  # LF index, CR immediately before
    fields = ", ".join(f"{name}_q[{w-1}:0]" for name, w, _ in EBRS)
    blocks = "".join(ebr(*e) for e in EBRS)
    return f'''// HB09P{"s" if once else ""}, generated by hb09p_gen.py. Raw PDP36, no forwarding mux.
// R<16 hex window LFSR><{HEX_SAMPLES} hex samples> CR LF, 115200 8N1.
// Each {SAMPLE_BITS}-bit sample: {{{fields}}}, first field in MSBs.
// Sample k is before edge k; sample k+1 reflects edge k (NOREG).
module top(input clk_25mhz, output ftdi_rxd);
  function [63:0] step_lfsr(input [63:0] x);
    reg [63:0] t;
    integer i;
    begin
      t = x;
      for (i = 0; i < {LFSR_STEPS}; i = i + 1)
        t = {{t[62:0], t[63] ^ t[62] ^ t[60] ^ t[59]}};
      step_lfsr = t;
    end
  endfunction
  reg [63:0] lfsr = 64'h{SEED:016X};
  wire [1:0] wa = lfsr[1:0];
  wire [1:0] ra = lfsr[5] ? wa : lfsr[3:2];
  wire we = lfsr[4];
  wire [35:0] data = lfsr[41:6];
{blocks}
  wire [{SAMPLE_BITS-1}:0] sample = {{{fields}}};
  reg [63:0] win_lfsr = 64'h{SEED:016X};
  reg [{(SAMPLES-1).bit_length()-1}:0] u = 0;
  reg [{total-1}:0] rec = 0;
  localparam REC = 0, SEND = 1;
  reg state = REC;
  reg [{last.bit_length()-1}:0] ci = 0;
  function [7:0] hex(input [3:0] v);
    hex = v < 10 ? 8'h30 + v : 8'h37 + v;
  endfunction
  reg [7:0] ch;
  always @* begin
    if (ci == 0) ch = "R";
    else if (ci < 17) ch = hex(win_lfsr[63 - 4*(ci-1) -: 4]);
    else if (ci < {17+HEX_SAMPLES}) ch = hex(rec[{total-1} -: 4]);
    else if (ci == {last-1}) ch = 8'h0d;
    else ch = 8'h0a;
  end
  reg tx = 1, busy = 0;
  reg [7:0] baud = 0;
  reg [3:0] bitn = 0;
  reg [9:0] shift = 10'h3ff;
  always @(posedge clk_25mhz) begin
    lfsr <= step_lfsr(lfsr);
    case (state)
      REC: begin
        if (u == 0) win_lfsr <= lfsr;
        rec <= {{rec[{total-SAMPLE_BITS-1}:0], sample}};
        u <= u + 1;
        if (u == {SAMPLES-1}) begin state <= SEND; u <= 0; end
      end
      SEND:
        if (!busy) begin
          shift <= {{1'b1, ch, 1'b0}};
          busy <= 1; baud <= 0; bitn <= 0;
        end else if (baud == 216) begin
          baud <= 0; tx <= shift[0]; shift <= {{1'b1, shift[9:1]}};
          bitn <= bitn + 1;
          if (bitn == 9) begin
            busy <= 0;
            if (ci >= 17 && ci < {17+HEX_SAMPLES})
              rec <= {{rec[{total-5}:0], rec[{total-1} -: 4]}};
            if (ci == {last}) begin ci <= 0; state <= {"SEND" if once else "REC"}; end
            else ci <= ci + 1;
          end
        end else baud <= baud + 1;
    endcase
  end
  assign ftdi_rxd = tx;
endmodule
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("variant", nargs="?", choices=["s"])
    args = parser.parse_args()
    print(generate(args.variant == "s"), end="")
