"""Write hb02.v: what an EBR's output latch holds after configuration,
before its port has read (HB02). Usage: python3 hb02_gen.py > hb02.v

Eight DP16KD hold all ones but for the first chunk of INITVAL_00 (0x000A5)
and sit at word address 5. Their CE is low from configuration on, so the
outputs show the latch as configuration left it; e7 reads at every clock
as a control. The first 16 samples, from the first clock, are sent again and
again."""

# name, DATA_WIDTH_A, REGMODE_A, GSR, RESETMODE, CEA, DATA_WIDTH_B
EBRS = [
    ("e0", 9, "NOREG", "DISABLED", "ASYNC", 0, 18),   # as yosys maps a 2048x8 memory
    ("e1", 9, "NOREG", "ENABLED", "ASYNC", 0, 18),
    ("e2", 9, "OUTREG", "DISABLED", "ASYNC", 0, 18),
    ("e3", 18, "NOREG", "DISABLED", "ASYNC", 0, 18),
    ("e4", 36, "NOREG", "DISABLED", "ASYNC", 0, 36),  # nextpnr writes PDPW16KD
    ("e5", 1, "NOREG", "DISABLED", "ASYNC", 0, 1),
    ("e6", 9, "NOREG", "DISABLED", "SYNC", 0, 9),
    ("e7", 9, "NOREG", "DISABLED", "ASYNC", 1, 9),    # control: reads at every clock
]
# The bits each records, MSB first: (name, port, width)
RECORD = [("e0", "a", 9), ("e0", "b", 9), ("e1", "a", 9), ("e2", "a", 9), ("e3", "a", 18),
          ("e4", "a", 18), ("e4", "b", 18), ("e5", "a", 1), ("e6", "a", 9), ("e7", "a", 9)]
WIDTH = sum(w for *_, w in RECORD)
PAD = -WIDTH % 4
SAMPLES = 16
ALL_ONES = (1 << 320) - 1


def address(width):
    """The ADA/ADB bits of word address 5 at this width (EBR_ADDRESSING.md)."""
    low = {1: 0, 2: 1, 4: 2, 9: 3, 18: 4, 36: 5}[width]
    word = 5 << low
    if width == 36:
        word |= 0xF  # byte enables
    return [word >> k & 1 for k in range(14)]


def ebr(name, wa, regmode, gsr, resetmode, cea, wb):
    ports = [f".DIA{i}(1'b0)" for i in range(18)] + [f".DIB{i}(1'b0)" for i in range(18)]
    ports += [f".ADA{i}(1'b{b})" for i, b in enumerate(address(wa))]
    ports += [f".ADB{i}(1'b{b})" for i, b in enumerate(address(wb if wa != 36 else 36))]
    ports += [f".DOA{i}({name}_a[{i}])" for i in range(18)]
    ports += [f".DOB{i}({name}_b[{i}])" for i in range(18)]
    ports += [".CLKA(clk_25mhz)", ".CLKB(clk_25mhz)", f".CEA(1'b{cea})", ".CEB(1'b0)",
              ".OCEA(1'b1)", ".OCEB(1'b1)", ".WEA(1'b0)", ".WEB(1'b0)",
              ".RSTA(1'b0)", ".RSTB(1'b0)",
              ".CSA0(1'b0)", ".CSA1(1'b0)", ".CSA2(1'b0)",
              ".CSB0(1'b0)", ".CSB1(1'b0)", ".CSB2(1'b0)"]
    params = [f".DATA_WIDTH_A({wa})", f".DATA_WIDTH_B({wb})",
              f'.REGMODE_A("{regmode}")', f'.REGMODE_B("{regmode}")',
              f'.RESETMODE("{resetmode}")', f'.GSR("{gsr}")']
    init = [f".INITVAL_{k:02X}(320'h{(ALL_ONES & ~0xFFFFF | 0x000A5) if k == 0 else ALL_ONES:080X})"
            for k in range(64)]
    return (f"  wire [17:0] {name}_a, {name}_b;\n"
            f"  DP16KD #({', '.join(params + init)}) {name} (\n    "
            + ",\n    ".join(ports) + ");\n")


rows = "".join(f"//   {n}    {wa:<4} {rm:<7} {g:<9} {r:<6} {c}    {wb}\n" for n, wa, rm, g, r, c, wb in EBRS)
fields = ", ".join(f"{n}_{p}[{w - 1}:0]" for n, p, w in RECORD)
print(f"""// HB02 slice: what an EBR output latch holds after configuration (B02).
// Generated by hb02_gen.py.
// Eight DP16KD at word address 5, every word all ones but the first
// INITVAL chunk (0x000A5); WEA = WEB = 0, RST low, OCE high, CEB low.
//   name  DATA_WIDTH_A  REGMODE  GSR  RESETMODE  CEA  DATA_WIDTH_B
{rows}// Sample ({WIDTH + PAD} bits) = {{{" ".join(f"{n}.DO{p.upper()}[{w - 1}:0]" for n, p, w in RECORD)}, {PAD}'b0}}
// at every 25 MHz edge from the first, taken before the edge. Line
// "B<{(WIDTH + PAD) * SAMPLES // 4} hex>": the first {SAMPLES} samples, the first in the MSBs, sent
// again and again.
module top(input clk_25mhz, output ftdi_rxd);
{"".join(ebr(*e) for e in EBRS)}  wire [{WIDTH + PAD - 1}:0] s = {{{fields}, {PAD}'b0}};
  reg [4:0] u = 0;
  reg [{(WIDTH + PAD) * SAMPLES - 1}:0] rec = 0;
  localparam REC = 0, SEND = 1;
  reg state = REC;
  function [7:0] hex(input [3:0] v);
    hex = v < 10 ? 8'h30 + v : 8'h37 + v;
  endfunction
  localparam N = {(WIDTH + PAD) * SAMPLES // 4};
  reg [9:0] ci = 0;
  reg [7:0] ch;
  always @* begin
    if (ci == 0) ch = "B";
    else if (ci < N + 1) ch = hex(rec[{(WIDTH + PAD) * SAMPLES - 1} - 4 * (ci - 1) -: 4]);
    else if (ci == N + 1) ch = 8'h0d;
    else ch = 8'h0a;
  end
  reg tx = 1, busy = 0;
  reg [7:0] baud = 0;
  reg [3:0] bitn = 0;
  reg [9:0] shift = 10'h3ff;
  always @(posedge clk_25mhz)
    case (state)
      REC: begin
        rec <= {{rec[{(WIDTH + PAD) * (SAMPLES - 1) - 1}:0], s}};
        u <= u + 1;
        if (u == {SAMPLES - 1}) state <= SEND;
      end
      SEND:
        if (!busy) begin
          shift <= {{1'b1, ch, 1'b0}};
          busy <= 1; baud <= 0; bitn <= 0;
        end else if (baud == 216) begin
          baud <= 0;
          tx <= shift[0];
          shift <= {{1'b1, shift[9:1]}};
          bitn <= bitn + 1;
          if (bitn == 9) begin
            busy <= 0;
            if (ci == N + 2) ci <= 0;
            else ci <= ci + 1;
          end
        end else baud <= baud + 1;
    endcase
  assign ftdi_rxd = tx;
endmodule""")
