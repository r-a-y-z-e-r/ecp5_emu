"""Generate HC08 PLL profiles; the reporter is identical in every build."""
import argparse

PROFILES = {
    'A': ('CLKOP', True, False),
    'B': ('CLKOP', False, False),
    'C': ('INT_OP', True, False),
    'D': ('INT_OP', False, False),
    'E': ('INT_OP', False, True),
    'F': ('INT_OP', True, False),
    'G': ('INT_OP', True, False),
    'H': ('INT_OS', True, False),
}
BASE_PROFILES = tuple('ABCDE')
FOLLOWUP_PROFILES = tuple('FGH')
# F/G change only C's unused CLKOS3 divider. H changes F's selector to INT_OS.
CLKOS3_DIV = {'F': 3, 'G': 2, 'H': 3}
ANALOG = dict(ICP_CURRENT=12, LPF_RESISTOR=8,
              MFG_ENABLE_FILTEROPAMP=1, MFG_GMCREF_SEL=2)


def generate(profile):
    feedback, analog, internal_return = PROFILES[profile]
    attrs = ', '.join(f'{k}="{v}"' for k, v in ANALOG.items())
    extra = f", .CLKOS3_DIV({CLKOS3_DIV[profile]})" if profile in CLKOS3_DIV else ''
    return f'''// HC08 {profile}: generated by gen.py. UART never uses the PLL clock.
module top(input clk_25mhz, output ftdi_rxd);
  (* keep=1 *) wire clkop, locked;
  wire fb;
  (* FREQUENCY_PIN_CLKI="25", FREQUENCY_PIN_CLKOP="100" *)
  {('(* ' + attrs + ' *)') if analog else '// Analog attributes deliberately absent.'}
  EHXPLLL #(.PLLRST_ENA("DISABLED"), .INTFB_WAKE("DISABLED"),
    .STDBY_ENABLE("DISABLED"), .DPHASE_SOURCE("DISABLED"),
    .OUTDIVIDER_MUXA("DIVA"), .OUTDIVIDER_MUXB("DIVB"),
    .OUTDIVIDER_MUXC("DIVC"), .OUTDIVIDER_MUXD("DIVD"),
    .CLKI_DIV(1), .CLKFB_DIV(4), .FEEDBK_PATH("{feedback}"),
    .CLKOP_ENABLE("ENABLED"), .CLKOP_DIV(6), .CLKOP_CPHASE(2), .CLKOP_FPHASE(0){extra})
  pll(.CLKI(clk_25mhz), .CLKFB({'fb' if internal_return else 'clkop'}),
    .CLKINTFB({'fb' if internal_return else ''}), .CLKOP(clkop),
    .RST(1'b0), .STDBY(1'b0), .PHASESEL0(1'b0), .PHASESEL1(1'b0),
    .PHASEDIR(1'b1), .PHASESTEP(1'b1), .PHASELOADREG(1'b1),
    .PLLWAKESYNC(1'b0), .ENCLKOP(1'b0), .LOCK(locked));
  hc08_reporter reporter(.clk(clk_25mhz), .clkop(clkop),
    .locked(locked), .ftdi_rxd(ftdi_rxd));
endmodule
'''


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('profile', choices=PROFILES)
    print(generate(p.parse_args().profile), end='')
