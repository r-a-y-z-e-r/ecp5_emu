def rows(code):
    glyph = G[code]
    assert len(glyph) == 16, f"glyph {code}: {len(glyph)} rows, want 16"
    out = []
    for row in glyph:
        assert len(row) == 8 and set(row) <= {".", "#"}, f"glyph {code}: bad row {row!r}"
        out.append(int("".join("1" if c == "#" else "0" for c in row), 2))
    return out


def main():
    assert sorted(G) == list(range(32, 127)), "need exactly the 95 printable glyphs"
    image = [byte for code in range(32, 127) for byte in rows(code)]
    assert len(image) == 95 * 16
    if "--preview" in sys.argv:
        for code in range(32, 127):
            print(f"{code:3} {chr(code)!r}")
            for row in G[code]:
                print("   ", row.replace(".", " ").replace("#", "\u2588"))
        return
    path = __file__.rsplit("/", 1)[0] + "/font.hex"
    with open(path, "w") as f:
        for byte in image + [0] * (2048 - len(image)):
            f.write(f"{byte:02x}\n")
    print(f"{path}: 95 glyphs x 16 rows, 2048 bytes")


if __name__ == "__main__":
    main()
