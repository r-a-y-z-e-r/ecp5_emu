#!/usr/bin/env python3
"""Generate our sine, Hamming-windowed sinc and scalar-port DSP wrapper.
No third-party tables or numerical packages are needed.
"""
from pathlib import Path
import math
HERE=Path(__file__).resolve().parent
N=31
# fs = 2 kHz (top.v ticks one sample every 25e6/2000 clocks), cutoff 50 Hz.
# The normalized cutoff is 50/2000 = 0.025, what the 1 kHz sketch used.
FS,FC=2000,50
h=[]
for k in range(N):
    x=k-(N-1)/2
    sinc=2*FC/FS if x==0 else math.sin(2*math.pi*FC*x/FS)/(math.pi*x)
    h.append(sinc*(0.54-0.46*math.cos(2*math.pi*k/(N-1))))
c=[round(v/sum(h)*65536) for v in h]
c[15]+=65536-sum(c)
(HERE/'coeff.hex').write_text(''.join(f'{v & 0x3ffff:05x}\n' for v in c))
(HERE/'sine.hex').write_text(''.join(f'{round(65536*math.sin(2*math.pi*k/256)) & 0x3ffff:05x}\n' for k in range(256)))
def bus(port, net, count, offset=0):
    return ', '.join(f'.{port}{i}({net}[{i+offset}])' for i in range(count))
# The block's CE/RST lines are shared by its three cells, and nextpnr takes
# one net per line for the block (hd03 b2: a cell whose netlist line differs
# ends up on another cell's). Every cell therefore gets the SAME controls,
# rst included; with no register stages the MULT18s ignore theirs.
ctrl=".CLK0(clk), .CLK1(1'b0), .CLK2(1'b0), .CLK3(1'b0), .CE0(enable), .CE1(1'b1), .CE2(1'b1), .CE3(1'b1), .RST0(rst), .RST1(1'b0), .RST2(1'b0), .RST3(1'b0)"
s='''// Generated by generate.py: scalar ports are the native ECP5 interface.
// The first tap selects MA, all others select MA + the registered R.
// Flag clocking prevents nextpnr from bypassing part of the output bank.
// The ports are deliberately NOT declared signed: yosys re-elaborates a
// signed-port module from its AST at the final hierarchy check, after
// flatten has deleted the modules around it, and that re-elaboration
// fails ("Module `filters' ... is not part of the design"). Sign lives in
// the SIGNEDA/SIGNEDB pins and in the signed wires of filter.v instead.
//
// nextpnr refuses an ALU54B input port that does not come from a
// MULT18X18D ("No MULT18X18D found connected to ALU54B ... port B"), so a
// second multiplier with all-zero operands feeds B and MB with zero,
// exactly as docs/inventory/LFE5U-85F/hd05_alu54_chain/hd05.v wires its
// proven MULT18_0/MULT18_1/ALU54_3 triple. The BEL pins are that triple.
//
// The opcode is the CONSTANT 11'h25d (R = R + MA), never a net: in the
// emulator's fast mode an OP that is a runtime net can select every
// operand source, so the program reads them all — including the cascade
// CIN, which floats on a chain head ("fast mode reads ...JCIN0..., z").
// With a constant 25d it reads only MA, SIGNEDIA and the registered R.
// The first tap's "load" is therefore done with the ALU's own RST0 at the
// sample tick (reset has priority over the enable, HD07), not a second op.
module dsp_mac(input clk, input enable, input rst,
  input [17:0] a,b, output [53:0] result);
  wire [35:0] product;
  wire [17:0] roa,rob;
  wire signedp;
  wire [35:0] zero_product;
  wire [17:0] zero_roa,zero_rob;
  wire zero_signedp;
  wire [10:0] op=11'h25d;
  (* BEL="X13/Y58/MULT18_0" *)
  MULT18X18D #(.REG_INPUTA_CLK("NONE"),.REG_INPUTB_CLK("NONE"),
    .REG_INPUTC_CLK("NONE"),.REG_PIPELINE_CLK("NONE"),
    .REG_OUTPUT_CLK("NONE"),.GSR("ENABLED"),.RESETMODE("SYNC")) mult(
'''
s+=f'    {bus("A","a",18)},\n    {bus("B","b",18)},\n'
s+=', '.join(f'.C{i}(1\'b0)' for i in range(18))+',\n'
s+=f"    .SIGNEDA(1'b1),.SIGNEDB(1'b1),.SOURCEA(1'b0),.SOURCEB(1'b0),{ctrl},\n    {bus('P','product',36)},\n    {bus('ROA','roa',18)},\n    {bus('ROB','rob',18)}, .SIGNEDP(signedp));\n"
s+='''  (* BEL="X14/Y58/MULT18_1" *)
  MULT18X18D #(.REG_INPUTA_CLK("NONE"),.REG_INPUTB_CLK("NONE"),
    .REG_INPUTC_CLK("NONE"),.REG_PIPELINE_CLK("NONE"),
    .REG_OUTPUT_CLK("NONE"),.GSR("ENABLED"),.RESETMODE("SYNC")) mult_zero(
'''
s+=', '.join(f'.A{i}(1\'b0)' for i in range(18))+',\n'
s+=', '.join(f'.B{i}(1\'b0)' for i in range(18))+',\n'
s+=', '.join(f'.C{i}(1\'b0)' for i in range(18))+',\n'
s+=f"    .SIGNEDA(1'b1),.SIGNEDB(1'b1),.SOURCEA(1'b0),.SOURCEB(1'b0),{ctrl},\n    {bus('P','zero_product',36)},\n    {bus('ROA','zero_roa',18)},\n    {bus('ROB','zero_rob',18)}, .SIGNEDP(zero_signedp));\n"
s+='''  (* BEL="X16/Y58/ALU54_3" *)
  ALU54B #(.REG_OUTPUT0_CLK("CLK0"),.REG_OUTPUT1_CLK("CLK0"),
    .REG_OUTPUT0_RST("RST0"),.REG_OUTPUT1_RST("RST0"),
    .REG_FLAG_CLK("CLK0"),.GSR("ENABLED"),.RESETMODE("SYNC")) alu(
'''
s+=bus('A','roa',18)+', '+', '.join(f'.A{i+18}(rob[{i}])' for i in range(18))+',\n'
s+=bus('B','zero_roa',18)+', '+', '.join(f'.B{i+18}(zero_rob[{i}])' for i in range(18))+',\n'
s+=bus('MA','product',36)+',\n'+bus('MB','zero_product',36)+',\n'
s+=', '.join(f'.C{i}(1\'b0)' for i in range(54))+',\n'
s+=f"    {bus('OP','op',11)}, .SIGNEDIA(signedp),.SIGNEDIB(zero_signedp),{ctrl},\n    {bus('R','result',54)});\nendmodule\n"
(HERE/'dsp_mac.v').write_text(s)
# Simulation models implement only the combinational signed multiplier and
# registered MA / MA+R used above. Unsupported settings fail the simulation.
params='''parameter REG_INPUTA_CLK="NONE",REG_INPUTB_CLK="NONE",REG_INPUTC_CLK="NONE",REG_PIPELINE_CLK="NONE",REG_OUTPUT_CLK="NONE",GSR="ENABLED",RESETMODE="SYNC"'''
ports=[f'input {p}{i}' for p,n in [('A',18),('B',18),('C',18)] for i in range(n)]
ports+=['input SIGNEDA,SIGNEDB,SOURCEA,SOURCEB,CLK0,CLK1,CLK2,CLK3,CE0,CE1,CE2,CE3,RST0,RST1,RST2,RST3']
ports += [f'output {p}{i}' for p,n in [('P',36),('ROA',18),('ROB',18)] for i in range(n)]+['output SIGNEDP']
m=f'module MULT18X18D #({params})('+','.join(ports)+');\n'
concat=lambda p,n:'{'+','.join(f'{p}{i}' for i in reversed(range(n)))+'}'
m+=f'wire signed [17:0] a={concat("A",18)},b={concat("B",18)};\n'
m+=f'assign {concat("P",36)}=a*b;\nassign {concat("ROA",18)}=a;\nassign {concat("ROB",18)}=b;\nassign SIGNEDP=1;\nendmodule\n'
ports=[f'input {p}{i}' for p,n in [('A',36),('B',36),('MA',36),('MB',36),('C',54),('OP',11)] for i in range(n)]
ports+=['input SIGNEDIA,SIGNEDIB,CLK0,CLK1,CLK2,CLK3,CE0,CE1,CE2,CE3,RST0,RST1,RST2,RST3']
ports += [f'output R{i}' for i in range(54)]
m+='module ALU54B #(parameter REG_OUTPUT0_CLK="CLK0",REG_OUTPUT1_CLK="CLK0",REG_OUTPUT0_RST="RST0",REG_OUTPUT1_RST="RST0",REG_FLAG_CLK="CLK0",GSR="ENABLED",RESETMODE="SYNC")('+','.join(ports)+');\n'
m+=f'''reg signed [53:0] r=0;
wire signed [35:0] ma={concat('MA',36)};
wire [10:0] op={concat('OP',11)};
assign {concat('R',54)}=r;
always @(posedge CLK0) begin
  if(RST0) r<=0;
  else if(CE0) begin
    case(op)
      11'h20d:r<=ma;
      11'h25d:r<=r+ma;
      default:$fatal(1,"Unsupported ALU opcode %h",op);
    endcase
  end
end
endmodule
'''
(HERE/'sim/dsp_models.v').write_text(m)
print('31 taps, sum',sum(c),'range',min(c),max(c))
